# AUTO-ADVANCE-ROOM time-confidence threshold: time spent in the current room
# must be at least this fraction of the heuristic expected-per-room duration
# before a transient non-run phase is trusted as a genuine room completion.
# Conservative (0.5) since expected_room_sec is a uniform-split heuristic, not
# a true per-room estimate — large rooms legitimately take longer than average.
_ROOM_TRANSITION_MIN_ELAPSED_RATIO: float = 0.5
#: A travel edge sooner than this after entering a room reads as
#: repositioning within it, not as a second boundary. Judgement, not
#: measurement: the confirmed room crossings measured 8-32 s, and no
#: intra-room hop was ever timed.
_ROOM_TRANSITION_MIN_SECONDS: float = 60.0
#: A travel edge sooner than this after entering a room reads as
#: repositioning within it, not as a second boundary.
#: A drive shorter than this is repositioning within a room, not a
#: boundary crossing. Set under the shortest confirmed crossing.


def _observed_rooms(entry: Any) -> list[str]:
    """Rooms the tracker actually advanced through this mission.

    `planned_rooms[:current_room_idx + 1]` -- the current room included,
    because reaching it means the robot worked there; advancing INTO a
    room is what confirms the previous one finished.

    Empty when nothing was tracked, which the caller treats as "fall
    back to the requested list" rather than "no rooms were cleaned".
    """
    try:
        store = getattr(
            getattr(entry, "runtime_data", None), "mission_timer_store", None
        )
        planned = list(getattr(store, "planned_rooms", None) or [])
        if not planned:
            return []
        index = int(getattr(store, "current_room_idx", 0) or 0)
        return planned[: max(0, min(index, len(planned) - 1)) + 1]
    except Exception:  # noqa: BLE001
        return []


def _remember_measured_room_time(
    entry: Any, room: str | None, seconds: float | None,
    mode: int | None = None,
) -> None:
    """Keep what a room actually took, so the next mission has a figure.

    STORED IMMEDIATELY, on one observation. The alternative was a
    confidence rule of our own -- wait for N runs, discard outliers --
    and the thing it would be compared against is a whole-house average
    divided by room count. A single real measurement of this room beats
    that on its first attempt, so waiting only prolongs the bad figure.

    A mission with a stuck robot or a mid-run recharge will record a
    long time. That is a worse estimate than a good run and a better one
    than 5.9 hours.

    Keyed the same way the cloud estimates are, so the two share a
    lookup and a later mission with real cloud data still wins.
    """
    if not room or not seconds or seconds <= 0:
        return
    try:
        profile = getattr(
            getattr(entry, "runtime_data", None), "robot_profile_store", None
        )
        if profile is None:
            return
        cache = getattr(profile, "room_estimate_cache", None)
        if cache is None:
            return
        # THE SAME KEY THE LOOKUP USES, or the write is unreachable.
        #
        # `cached_room_seconds()` searches by the prefix
        # "<region_id>|", because cloud estimates are stored per
        # parameter set. A bare room name would sit in the same dict and
        # never be found -- which is precisely the failure this whole
        # change exists to repair, so it is worth not repeating.
        #
        # "measured" as the parameter part: honest about where it came
        # from, and distinct from any cloud entry for the same room.
        # A RUNNING MEAN, PER CLEANING MODE.
        #
        # This stored the last measurement, so a room swung with each
        # run: @ScenicSystemsLLC's Guest Bathroom went 232 -> 220 ->
        # 197 -> 250 seconds across four missions, a 25% spread that
        # the estimate followed exactly. A mean settles.
        #
        # PER MODE, because they are not the same room to a robot. A
        # mop pass and a vacuum pass over the same floor take different
        # times, and averaging them together produces a figure that
        # describes neither. The cloud keys its own estimates by
        # parameters for the same reason.
        #
        # An unknown mode gets its own bucket rather than being folded
        # into a known one -- mixing is the thing being avoided.
        _key = f"{room}|measured|{mode if mode is not None else 'unknown'}"
        _count_key = f"{_key}|count"

        _n = int(cache.get(_count_key, 0) or 0)
        _mean = float(cache.get(_key, 0.0) or 0.0)
        if _n > 0 and _mean > 0:
            _mean = (_mean * _n + float(seconds)) / (_n + 1)
            _n += 1
        else:
            _mean, _n = float(seconds), 1

        # STORED UNROUNDED. Rounding at each step compounds: four runs
        # averaging 224.75 came out as 224.7 because every intermediate
        # mean lost a digit. The readers round when they present it.
        cache[_key] = _mean
        cache[_count_key] = float(_n)
        _LOGGER.debug(
            "AUTO-ADVANCE-ROOM: measured %s at %.0fs, kept for next time "
            "(the cloud offers no per-room estimate in auto pass mode)",
            room, seconds,
        )
    except Exception:  # noqa: BLE001
        return


def _room_transition_confidence_ok(
    mission: dict[str, Any],
    mts: Any,
    *,
    from_travel: bool = False,
) -> bool:
    """AUTO-ADVANCE-ROOM (v2.8.0) confidence check.

    Combines four signals (per community feature request from Thonno) to
    decide whether a transient non-run cleanMissionStatus phase represents a
    genuine inter-room transition, as opposed to an error, a user pause, or a
    genuine low-battery recharge that happens to pass through the same phase
    string ("charge").

    Conditions (ALL must hold):
      1. No active error on the mission (mission.error == 0).
      2. cycle is still "clean" or "quick" — robot has not reported mission end.
      3. expected_room_sec is available AND time_in_current_room_sec is at
         least _ROOM_TRANSITION_MIN_ELAPSED_RATIO of the expected per-room
         duration.

    v2.8.0 (live wiring): the call site in this module now computes real
    per-room cloud TE1 time estimates via _compute_room_time_estimates() and
    passes them through set_mission_plan(room_estimates_sec=...), so
    expected_room_sec is populated whenever cloud data is available for the
    current room (falling back to a uniform total_estimated_sec / room_count
    split otherwise). AUTO-ADVANCE-ROOM is therefore live, not dormant, as
    long as at least a uniform estimate can be derived.

    Condition 2 shares the same cycle field as the INTER-ROOM-TRANSITION
    guard above and is subject to the same known reliability caveat — see
    the v2.8.1 END-DEBOUNCE comment on that guard. A cycle misread here would
    simply suppress an auto-advance (conservative failure mode) rather than
    corrupt state, so no debounce was added on this path.
    """
    error_code = mission.get("error", 0) or 0
    if error_code:
        _LOGGER.debug(
            "AUTO-ADVANCE-ROOM: confidence check failed — "
            "active error_code=%d",
            error_code,
        )
        return False

    cycle = mission.get("cycle", "")
    if cycle not in ("clean", "quick"):
        _LOGGER.debug(
            "AUTO-ADVANCE-ROOM: confidence check failed — "
            "cycle=%r not in (clean, quick)",
            cycle,
        )
        return False

    # THE TRAVEL ROUTE NEEDS NO ESTIMATE, so it must not be refused for
    # the want of one.
    #
    # This check sat ABOVE the travel branch, so a robot with no cloud
    # estimates at all had every travel-based advance refused -- on the
    # strength of a missing forecast, while holding a positive
    # observation that the robot had cleaned this room and then driven
    # away.
    #
    # That is the rule this file keeps relearning: an estimate may
    # refine a decision, never be the sole reason to refuse one. It cost
    # a stuck display three times over -- a missing estimate, a poisoned
    # one, and a travel-duration floor, each blocking something an
    # observation had already answered.
    #
    # The phase route still needs it: a `charge` mid-room and a `charge`
    # at a room boundary look identical, and only timing tells them
    # apart.
    if from_travel:
        return bool(
            mts.time_in_current_room_sec >= _ROOM_TRANSITION_MIN_SECONDS
        )

    expected = mts.expected_room_sec
    if expected is None or expected <= 0:
        _LOGGER.debug(
            "AUTO-ADVANCE-ROOM: confidence check failed — "
            "expected_room_sec=%s (no per-room or total estimate available)",
            expected,
        )
        return False  # cannot confirm timing — conservative refusal (see docstring)

    elapsed = mts.time_in_current_room_sec

    # A TRAVEL EDGE IS NOT A TIMING GUESS.
    #
    # The ratio below asks "has this room had roughly enough time to be
    # finished". That is the right question for the PHASE route, where
    # a `charge` in the middle of a room must not read as a room change.
    #
    # It is the wrong question for a travel edge. The robot has said it
    # was DRIVING and then stopped driving; how long it had been in the
    # previous room does not bear on whether it left.
    #
    # WHAT IT COST: @Thonno's i7+ moved from Kitchen to Bathroom and the
    # display followed NINE MINUTES LATER -- which is half of what this
    # project estimates his kitchen takes. The travel signal fired on
    # time and was held back by a clock.
    #
    # A FLOOR REMAINS, because a travel edge is not always a room
    # boundary: @ScenicSystemsLLC watched one that was repositioning
    # inside a single undivided hallway. A drive ending less than a
    # minute after entering a room is far more likely to be that than a
    # second room boundary.
    #
    # The minute is judgement, not measurement. It is the first thing to
    # revisit if rooms start advancing too eagerly.
    _ok = elapsed >= expected * _ROOM_TRANSITION_MIN_ELAPSED_RATIO
    if not _ok:
        _LOGGER.debug(
            "AUTO-ADVANCE-ROOM: confidence check failed — "
            "elapsed=%.1fs < expected=%.1fs * ratio=%.2f (room finished "
            "faster than estimated, or robot just entered it)",
            elapsed, expected, _ROOM_TRANSITION_MIN_ELAPSED_RATIO,
        )
    return bool(_ok)


# ── Partial-message-safe top-level key lookup ───────────────────────────────

def _mission_recovered_after_stuck(
    entry: RoombaConfigEntry, mission: dict[str, Any], stuck_at: float
) -> bool | None:
    """Did this mission carry on after its stuck event?

    Answered from what the mission RECORDED rather than from a live
    clock, because the clock it replaces was measuring the wrong thing:
    `stuck_cleared_ts` is rewritten on every re-entry into an active
    phase, so a mission that resumed and then cleaned for hours read as
    abandoned whenever its final room ran short.

    Two signals, both already in the cloud record, and both counted only
    AFTER `stuck_at` (wall clock, compared with the record's own Unix
    timestamps):

      - a pass the robot finished (status 0 or 1). A robot that gave up
        finishes none -- but it may well have finished rooms BEFORE it got
        stuck, and those were counted too, so a mission that cleaned two
        rooms and gave up in the third read as resumed and counted as
        completed. Status 5 and 6 do not count at all: they are events the
        firmware closes at mission END, which says the mission stopped,
        not that the robot worked on.
      - a `travel` to the dock, which is how a mission ends when the robot
        drove home rather than being cancelled or expiring.

    Returns None when the record is not available -- a Prime robot, a
    local-only setup, the cloud not having caught up -- or when the stuck
    time is unknown. The caller then falls back to the old elapsed-time
    test, which is wrong in one direction but better than refusing to
    classify.
    """
    if not stuck_at:
        return None
    cc = getattr(entry.runtime_data, "cloud_coordinator", None)
    if cc is None:
        return None
    mission_id = mission.get("missionId") or mission.get("mission_id")
    if not mission_id:
        return None

    def _after_stuck(ev: dict[str, Any]) -> bool:
        # A room event carries its start (`ts`) and its end (`ets`); the
        # end is what must come after the stuck. A travel event has `ts`.
        when = ev.get("ets") or ev.get("ts")
        try:
            return when is not None and float(when) > stuck_at
        except (TypeError, ValueError):
            return False

    for record in getattr(cc, "raw_records", None) or []:
        if not isinstance(record, dict):
            continue
        if record.get("missionId") != mission_id:
            continue
        timeline = record.get("timeline")
        if not isinstance(timeline, dict):
            return None
        events = [ev for ev in timeline.get("finEvents") or [] if isinstance(ev, dict)]

        worked_on = any(
            ev.get("type") == "room"
            and (ev.get("room") or {}).get("status") in ROOM_EVENT_PASS_DONE_STATUSES
            and _after_stuck(ev)
            for ev in events
        )
        docked = any(
            ev.get("type") == "travel"
            and (ev.get("travel") or {}).get("dest") == "dock"
            and _after_stuck(ev)
            for ev in events
        )
        # EITHER is enough. A mission that finished a pass after being
        # freed did not abandon, whatever its ending; and one that drove
        # home under its own power did not abandon either.
        return worked_on or docked

    return None


def _merged_top_level(
    entry: RoombaConfigEntry,
    reported: dict[str, Any],
    key: str,
) -> dict[str, Any]:
    """Return reported[key], falling back to the cached master_state's
    same key when this message's `reported` doesn't carry it at all.

    MQTT messages are deltas — a message that updates cleanMissionStatus
    (e.g. a phase transition) is not guaranteed to also carry bbrun,
    runtimeStats, bbchg3, pose, or lastCommand, since those are separate
    top-level keys. Reading reported.get(key, {}) directly on exactly the
    message that triggered a phase-transition handler silently substitutes
    an empty/zero default for the robot's actual last-known value.

    Harmless for "this round only" reads that get a fresh chance on the
    next message. Wrong for BASELINE/SNAPSHOT reads — nStuck-at-start,
    zone names captured at mission start, or per-mission analytics
    recorded exactly once at mission end — where a wrong default becomes
    a permanent, never-self-correcting error (e.g. a clean mission
    misclassified as stuck_and_resumed because nStuck's baseline was
    wrongly read as 0 instead of the robot's true lifetime count).
    """
    value = reported.get(key)
    if value:
        return dict(value)
    roomba = getattr(entry.runtime_data, "roomba", None)
    master = getattr(roomba, "master_state", None) or {}
    return ((master.get("state") or {}).get("reported") or {}).get(key) or {}


# ── Zone-name capture ─────────────────────────────────────────────────────────

def _capture_zone_names(
    entry: RoombaConfigEntry,
    reported: dict[str, Any],
) -> list[str]:
    """Resolve zone names at mission start for all robot types.

    ROOM-SEG Stage 6 — EPHEMERAL branch backed by RoomSegStore, not
    ZoneStore (deleted — gap heuristic proved unreliable, see
    ROOM_SEGMENTATION_NOTES.md).
    """
    from .models import MapCapability

    data: RoombaData = entry.runtime_data
    if data.room_seg_store:                      # EPHEMERAL
        return [r.name for r in data.room_seg_store.rooms.values() if r.confirmed]
    if data.map_capability == MapCapability.SMART:
        last_cmd = _merged_top_level(entry, reported, "lastCommand")
        region_ids = [
            r.get("region_id")
            for r in (last_cmd.get("regions") or [])
            if r.get("region_id")
        ]
        if region_ids and data.cloud_coordinator:
            # Across every map: a mission can target a room on a map
            # the robot is not currently using, and this is the lookup
            # that names the rooms it visits.
            id_to_name = region_names_across_maps(data.cloud_coordinator)
            return [id_to_name[rid] for rid in region_ids if rid in id_to_name]
    return []  # NONE (600-series) or SMART without cloud


def _mission_already_terminal(entry: RoombaConfigEntry, mssn_strt_tm: int) -> bool:
    """MissionStore already holds a terminal record for this mssnStrtTm
    whose ended_at is within the MQTT re-delivery window -- i.e. a phase
    flipping back to run/hmMidMsn/evac under the same mssnStrtTm is a
    post-terminal replay pulse, not a new mission start.

    A terminal record older than the window means a genuine new segment
    (980/900-series multi-recharge keeps mssnStrtTm across segments), so
    older terminal records do not suppress.
    """
    if not mssn_strt_tm:
        return False
    data: RoombaData = entry.runtime_data
    store = data.mission_store
    if store is None:
        return False
    from .mission_store import MissionStore
    candidate_id = f"m_{mssn_strt_tm}"
    now = dt_util.utcnow()
    for r in store.records:
        if (
            MissionStore.base_mission_id(r.get("id")) == candidate_id
            and MissionStore.is_terminal_result(r.get("result"))
        ):
            ended = r.get("ended_at")
            ended_dt = dt_util.parse_datetime(ended) if ended else None
            if ended_dt is None or (now - ended_dt).total_seconds() <= _CLOUD_CATCHUP_MISSION_MATCH_SEC:
                return True
    return False


# ── Mission record builder ────────────────────────────────────────────────────

async def async_record_mission(
    hass: Any,
    entry: RoombaConfigEntry,
    mission: dict[str, Any],
    reported: dict[str, Any],
    zones: list[str],
    start_ts: int,
    nstuck_delta: int,
    observed_rooms: list[str] | None = None,
    mission_error_code: int = 0,
    recharge_min: int = 0,
    result_override: str | None = None,
    npicks_delta: int = 0,
) -> None:
    """Build and append a mission record to MissionStore.

    Args:
        hass:            HomeAssistant instance (for storage and dt_util).
        entry:           Config entry whose runtime_data holds the MissionStore.
        mission:         cleanMissionStatus dict from the end-of-mission MQTT message.
        reported:        Full reported state dict from the same MQTT message.
        zones:           Zone names captured at mission START (not end).
        observed_rooms:  Rooms the tracker advanced through -- what was
                         actually worked in, where tracking ran.
        start_ts:        mssnStrtTm cached at mission START. The 980/900-series
                         firmware resets this field to 0 in the end MQTT message,
                         so it must be captured when the cleaning phase begins.
        nstuck_delta:    bbrun.nStuck delta since mission start. Using the delta
                         rather than the lifetime counter prevents marking every
                         mission as stuck when bbrun arrives in the same packet.
        npicks_delta:    v3.2.0 ANOMALY-EXPLAIN — bbrun.nPicks delta since mission
                         start, same delta-not-lifetime-counter reasoning as
                         nstuck_delta. >0 means the robot was physically picked
                         up during this mission. Unlike nstuck_delta (only used
                         to derive `result`), this IS stored directly on the
                         record — there's no other field it could be inferred
                         from later.
        recharge_min:    F4e — minutes spent recharging mid-mission, accumulated
                         from rechrgM fields across hmMidMsn phase entries.
        result_override: F6c — when set, overrides the computed result string
                         (e.g. "blocked_timeout" from BlockingManager).
    """
    data: RoombaData = entry.runtime_data
    if data.mission_store is None:
        return

    now = dt_util.utcnow()

    if start_ts:
        started_at = datetime.datetime.fromtimestamp(
            start_ts, datetime.timezone.utc
        )
    else:
        # Fallback: wall-clock at recording time (duration will be ~0).
        # Should not be reached after the closure fix — log for diagnostics.
        started_at = now
        _LOGGER.warning(
            "MissionStore: no cached start_ts for mission — duration will be 0"
        )

    phase = mission.get("phase", "")
    # THE MISSION, NOT THE LAST FRAME. `mission.error` is whatever the
    # end message carried; `mission_error_code` is whatever appeared at
    # any point. An error that fires mid-drive and clears itself -- the
    # 42 that filed a failed mission as `completed` -- is only in the
    # second.
    error_code: int = (mission.get("error", 0) or 0) or mission_error_code

    # F6c — result_override takes precedence (e.g. "blocked_timeout")
    if result_override:
        result = result_override
    elif error_code:
        result = "error"
    elif phase == "cancelled":
        result = "cancelled"
    elif nstuck_delta > 0:
        # F6h — default to stuck_and_abandoned; caller may override to
        # stuck_and_resumed if the phase returned to "run" after the stuck event.
        result = "stuck"
    else:
        result = "completed"

    elapsed_sec = (now - started_at).total_seconds()
    duration_min = max(0, round(elapsed_sec / 60))

    # Merge bbrun + runtimeStats — mirrors entity.py run_stats.
    # On i-series (lewis firmware) hr lives in runtimeStats, not bbrun.
    bbrun = _merged_top_level(entry, reported, "bbrun")
    runtime = _merged_top_level(entry, reported, "runtimeStats")
    bbrun_hr = bbrun.get("hr") or runtime.get("hr") or 0

    # v2.9.0 DAILY-DIGEST — chemistry-aware lifetime charge-cycle snapshot at
    # mission end, mirrors bbrun_hr above: a per-mission absolute-counter
    # snapshot, not a delta. api_views.py computes the cross-day delta the
    # same way it already does for bbrun_hr (filter_hours_today). None when
    # bbchg3 can be entirely absent (confirmed on 600-series AND on a j7+
    # running sapphire firmware — not a 600-series-exclusive phenomenon,
    # see MISSIONSTORE_FIELD_REGISTRY.md's raw vacuum_state findings).
    battery_cycles = active_charge_cycles(_merged_top_level(entry, reported, "bbchg3"))

    # F8b — capture error context at mission end
    # pose is None for firmware 3.20+ and 600-series; absent when null.
    error_position_mm: dict[str, Any] | None = None
    if error_code:
        _pose = _merged_top_level(entry, reported, "pose")
        pose_point = _pose.get("point") if _pose else None
        if pose_point:
            try:
                # v2.9.0 — firmware reports cm, not mm. See POSE_POINT_CM_TO_MM
                # in const.py.
                error_position_mm = {
                    "x": float(pose_point.get("x", 0)) * POSE_POINT_CM_TO_MM,
                    "y": float(pose_point.get("y", 0)) * POSE_POINT_CM_TO_MM,
                }
            except (TypeError, ValueError):
                pass

    phase_at_error: str | None = phase if error_code else None

    self_recovered: bool | None = (
        True  if result == "stuck_and_resumed"   else
        False if result == "stuck_and_abandoned" else
        None
    )

    # v3.2.0 TEAM-INDICATOR — was this mission part of an Imprint Link
    # team clean? lastCommand.params.team.team_id is only present when the
    # mission was started as part of a multi-robot team routine (confirmed
    # via KingAntDesigns' j7+ field data — three scheduled team routines +
    # the actual last mission run). Purely informational; None on ordinary
    # single-robot missions, which is the vast majority.
    last_cmd_for_team = _merged_top_level(entry, reported, "lastCommand")
    team_id: str | None = (
        (last_cmd_for_team.get("params") or {}).get("team") or {}
    ).get("team_id")

    record: dict[str, Any] = {
        "id": f"m_{int(started_at.timestamp())}",
        "started_at": started_at.isoformat(),
        "ended_at": now.isoformat(),
        "duration_min": duration_min,
        # v2.8.2: "or None" added — some robots (confirmed: 980 9-series with
        # aftermarket NiMH battery) report cleanMissionStatus.sqft as a literal
        # 0 rather than omitting the field, even for missions lasting hours.
        # Without this, the merge-precedence rule ("never overwrite a
        # non-None value") permanently locks out cloud backfill, even though
        # the cloud often has a real area value for the same mission. A
        # genuine 0-sqft mission is indistinguishable from "no data" anyway,
        # so this loses nothing and lets backfill work as intended.
        "area_sqft": mission.get("sqft") or None,   # None for 600-series — correct
        "result": result,
        "initiator": mission.get("initiator", "none"),
        "zones": zones,
        # WHAT WAS ACTUALLY CLEANED, alongside what was asked for.
        #
        # `zones` is resolved at mission START -- the request. A room
        # the robot never reached is in it all the same.
        #
        # The completed-room source is `timeline.finEvents`, and the
        # timeline is Prime-only. On Classic the resolution therefore
        # found nothing every time and the vacuum attribute held
        # whatever it had last managed to resolve: @ScenicSystemsLLC saw
        # all seven rooms of a whole-house run still listed after two
        # separate two-room missions.
        #
        # Room tracking now confirms transitions from observations on
        # both generations, so the rooms it advanced through are rooms
        # the robot worked in. Stored under the key the resolver already
        # falls back to, so no new source is needed -- the timeline
        # still wins where it exists, because it reports real
        # completions with a status.
        "last_cleaned_rooms": observed_rooms or zones,
        "error_code": error_code if error_code else None,
        "bbrun_hr": bbrun_hr,
        "battery_cycles": battery_cycles,   # v2.9.0 DAILY-DIGEST
        "recharge_min": recharge_min if recharge_min > 0 else None,  # F4e
        # F8b — error context fields (None when no error or no pose data)
        "error_position_mm": error_position_mm,
        "phase_at_error":    phase_at_error,
        "self_recovered":    self_recovered,
        "team_id": team_id,   # v3.2.0 TEAM-INDICATOR
        "npicks_delta": npicks_delta,   # v3.2.0 ANOMALY-EXPLAIN
    }

    if not data.mission_store.update_terminal_fields(record["id"], record):
        await data.mission_store.async_append(record)
    await data.mission_store.async_save(hass, entry.entry_id)

    # v3.1.0 L9-MAP — update the personal relocalisation baseline.
    # Same gate as the MissionStore record itself (this function only runs
    # when had_cleaning_phase was True, i.e. a genuine cleaning mission
    # occurred) — avoids polluting the baseline with the automatic nMssn
    # increments that happen at "mission ready" without any actual cleaning
    # (field-confirmed by Thonno: mssnNavStats resets to near-zero values on
    # those pseudo-missions, which would corrupt a baseline meant to reflect
    # real navigation behaviour).
    rps = getattr(data, "robot_profile_store", None)
    if rps is not None:
        nav_stats = reported.get("mssnNavStats")
        # AN EMPTY RECORD IS NOT A MEASUREMENT OF ZERO.
        #
        # Two of three robots on the same `lewis` firmware report
        # `mssnNavStats` with EVERY counter at zero -- no landmarks
        # seen, none tracked, no relocalisations -- during a mission and
        # after it, unchanged. A robot navigating by vSLAM does not see
        # zero landmarks; the record is simply never populated on those
        # units (@veronoicc, i7+ and i8+).
        #
        # `reLc` feeds a per-robot percentile of localisation quality.
        # Taking those zeros as real readings fills that distribution
        # with values the robot never measured, and the percentile then
        # describes nothing.
        #
        # `gLmk` and `lmk` are the tell: a genuine record has landmarks
        # in it even when `reLc` is legitimately 0.
        _looks_populated = any(
            nav_stats.get(k) for k in ("gLmk", "lmk", "mTrk")
        ) if isinstance(nav_stats, dict) else False

        if isinstance(nav_stats, dict) and "reLc" in nav_stats and _looks_populated:
            try:
                relocs = int(nav_stats["reLc"])
            except (TypeError, ValueError):
                relocs = None
            if relocs is not None:
                rps.update_reloc_baseline(relocs)
                await rps.async_save(hass, entry.entry_id)
                # v3.5.0 Repairs redesign — the reloc_rate_elevated Repair
                # Issue was removed; RoombaRelocalisationRateSensor now
                # exposes percentile_rank directly (see
                # RobotProfileStore.reloc_percentile_rank()), computed
                # fresh from update_reloc_baseline() above whenever the
                # sensor is read — no separate check call needed here.

        # v3.1.0 L9-BATTERY — record this mission's estCap observation into
        # the noise-floor baseline. Same had_cleaning_phase gate as above —
        # a consistent per-mission cadence is what the noise-floor baseline
        # is meant to characterise; recording on every MQTT update instead
        # would mix in mid-mission jitter unrelated to charge-cycle deltas.
        bbchg3 = _merged_top_level(entry, reported, "bbchg3")
        raw_estcap = bbchg3.get("estCap")
        cycles_energy = active_charge_cycles(bbchg3)
        if raw_estcap:
            profile = data.robot_profile
            if profile is not None:
                estcap_mah = estcap_to_mah(
                    raw_estcap,
                    profile.estcap_scale_liion,
                    profile.estcap_scale_nimh,
                    bbchg3.get("nNimhChrg"),
                )
                if estcap_mah is not None:
                    rps.record_estcap_observation(estcap_mah)
                    # F12e — advance the lifetime energy high-water here,
                    # where RobotProfileStore is already being persisted:
                    # the sensor read path stays side-effect-free and a
                    # restart between polls cannot lose the floor.
                    voltage = profile.battery_voltage if profile else 14.8
                    energy_kwh = round(
                        estcap_mah * voltage * int(cycles_energy or 0) / 1_000_000, 3
                    )
                    if energy_kwh:
                        rps.update_energy_high_water(energy_kwh)
                    await rps.async_save(hass, entry.entry_id)

    # v2.9.0 EVENT-BUS — fire roomba_plus_mission_completed for automations.
    # entry_id + name included (unlike the older L6 presence events) so
    # multi-robot installs can filter without a separate lookup.
    #
    # v3.2.0 UX fix — the ANOMALY-EXPLAIN result is folded directly into
    # the payload instead of requiring the user to (a) know the
    # explain_mission service exists and (b) call it themselves after
    # every mission. The record was appended above, so explain_mission()
    # sees it; the computation is once-per-mission-end, negligible.
    # Payload shape is CONSTANT: the three explanation fields are always
    # present (null when not anomalous) so automation templates never
    # have to guard against missing keys depending on the mission.
    explanation = data.mission_store.explain_mission(record["id"]) or {}
    hass.bus.async_fire(
        EVENT_MISSION_COMPLETED,
        {
            "entry_id": entry.entry_id,
            "name": entry.title,
            "rooms_cleaned": len(zones),
            "area_sqft": record["area_sqft"],
            "stuck_count": nstuck_delta,
            "result": result,
            "is_anomalous": bool(explanation.get("is_anomalous", False)),
            "anomaly_reason": explanation.get("anomaly_reason"),
            "recommended_action": explanation.get("recommended_action"),
            "robot_lifted": bool(explanation.get("robot_lifted", False)),
        },
    )


    # F6g — reset consecutive skip counter on any successful completion
    if result == "completed" and data.maintenance_store is not None:
        if data.maintenance_store.consecutive_skips > 0:
            data.maintenance_store.consecutive_skips = 0
            _LOGGER.debug("MissionStore: consecutive_skips reset on completed mission")
            await data.maintenance_store.async_save(hass, entry.entry_id)

    # F6e — check for mixed schedule patterns after each mission
    # Guard: only fire when hass is fully initialised (has config attribute)
    if getattr(hass, "is_running", False):
        from .repairs import async_check_mixed_schedule, async_check_mission_anomaly
        entry.async_create_task(
            hass, async_check_mixed_schedule(hass, entry)
        )
        # L3 — check for consecutive anomalous missions after each append
        entry.async_create_task(
            hass, async_check_mission_anomaly(hass, entry)
        )

    # Update L3 runtime error state.
    # Only update on error/stuck — do NOT clear on completed so the last
    # error remains visible until the next error occurs.
    if result in ("error", "stuck", "stuck_and_resumed", "stuck_and_abandoned"):
        data.last_error_code = error_code if error_code else None
        data.last_error_at   = now.isoformat()
        data.last_error_zone = zones[0] if zones else None

    _LOGGER.debug(
        "MissionStore: recorded %s result=%s duration=%dmin zones=%s",
        record["id"], result, duration_min, zones,
    )


