def _umf_version_changed(
    coordinator: Any,
    entry: "RoombaConfigEntry",
) -> bool:
    """Return True when the active UMF version differs from the last aligned version."""
    current_version = coordinator.umf_data.get("version_id")
    if not current_version:
        return False
    aligner = entry.runtime_data.umf_aligner
    if aligner is None:
        return True
    return bool(aligner.pmap_version_id != current_version)


async def _async_realign(
    hass: HomeAssistant,
    entry: "RoombaConfigEntry",
    coordinator: Any,
) -> None:
    """Re-instantiate and run UmfAligner after a pmap version change."""
    from .umf_aligner import UmfAligner
    data = entry.runtime_data
    if not coordinator.umf_data.get("points2d") or not coordinator.regions:
        return
    if data.geometry_store is None:
        return
    aligner = UmfAligner(
        points2d=coordinator.umf_data["points2d"],
        regions=coordinator.regions,
        geometry_store=data.geometry_store,
        pmap_version_id=coordinator.umf_data.get("version_id", ""),
    )
    conf = await hass.async_add_executor_job(aligner.align)
    data.umf_aligner = aligner
    _LOGGER.info(
        "Roomba+ UmfAligner: re-aligned confidence=%.2f aligned=%s for %s",
        conf, aligner.aligned, entry.data[CONF_BLID],
    )


def _extract_traversal_umf_positions(
    records: list[dict[str, Any]],
    aligner: Any,
    min_missions: int = 3,
) -> list[tuple[float, float]]:
    """Return UMF door candidate positions confirmed by ≥min_missions traversal missions."""
    door_candidates = getattr(aligner, "_door_candidates", [])
    if len(door_candidates) < 2:
        return []
    missions_with_traversals = 0
    for record in records:
        timeline = record.get("timeline") or {}
        fin_events = timeline.get("finEvents", [])
        if any(e.get("type") == "traversal" for e in fin_events):
            missions_with_traversals += 1
        if missions_with_traversals >= min_missions:
            return list(door_candidates)
    _LOGGER.info(
        "GS-SMART-UMF: %d/%d missions with traversal events in last %d cloud records "
        "— need %d more complete room-specific cleans for bootstrap",
        missions_with_traversals, min_missions, len(records),
        max(0, min_missions - missions_with_traversals),
    )
    return []


async def _async_update_robot_profile_store(
    hass: Any,
    entry: "RoombaConfigEntry",
    mission_store: Any,
    robot_profile_store: Any,
) -> None:
    """Update RobotProfileStore from the latest MissionStore and GridStore data.

    v2.6.0 L5/L6 — called after each successful cloud refresh.
    Moved from __init__.py to callbacks.py (SETUP-SPLIT Teil B, v3.0.0).
    """
    from .const import SQFT_TO_M2
    changed = False

    # L3/L8: mission duration/area baseline
    if robot_profile_store.update_mission_stats(mission_store.query(days=30)):
        changed = True

    # L5: per-room dirtiness from latest record's timeline
    records = mission_store.query(days=1)
    if records:
        latest = records[-1]
        timeline = latest.get("timeline") or {}
        fin_events = timeline.get("finEvents", [])
        for event in fin_events:
            if event.get("type") != "room":
                continue
            room = event.get("room", {})
            if room.get("status") not in ROOM_EVENT_DONE_STATUSES:
                continue
            rid = str(room.get("rid", ""))
            pass_count = int(room.get("passCount", 0))
            # ROOM SIZE, not covered area. `update_room_dirt_index` divides
            # passes by the room's area. `totalArea or area` gave the room
            # size for a one-pass room and the covered union for a two-pass
            # one (totalArea only exists from the second pass on), so the
            # same room's density jumped with its pass count.
            area_sqft = room.get("area") or 0
            area_m2 = float(area_sqft) * SQFT_TO_M2
            if rid and pass_count > 0 and area_m2 > 0:
                robot_profile_store.update_room_dirt_index(rid, pass_count, area_m2)
                changed = True

        # v3.3.0 CROSS-CORR — pair the pending mission-start snapshot with
        # this record's cloud-enriched dirt count (the dirt field only
        # exists post-enrichment, never at local MQTT mission end).
        _dirt = latest.get("dirt")
        if isinstance(_dirt, (int, float)) and robot_profile_store.finalize_correlation(
            latest.get("started_at"), float(_dirt)
        ):
            changed = True

    # L6: navigation efficiency baseline from GridStore
    gs = getattr(entry.runtime_data, "grid_store", None)
    if gs is not None:
        try:
            ratio = gs.edge_coverage_ratio()
            if ratio is not None and ratio > 0:
                robot_profile_store.update_coverage_baseline(ratio)
                changed = True
        except Exception:  # noqa: BLE001
            # Swallowed on purpose -- a failed baseline update must not stop
            # the profile save below. Logged because silence here is how a
            # measurement that never lands looks exactly like a measurement
            # that was never taken: the sensor falls back to an estimate and
            # nothing in the log says why.
            _LOGGER.debug(
                "Roomba+: coverage baseline update failed", exc_info=True
            )

    # J: lifetime sqft staleness tracking
    try:
        _reported = dict(
            (entry.runtime_data.roomba.master_state if entry.runtime_data.roomba else {})
            .get("state", {}).get("reported", {})
        )
        _bbrun = _reported.get("bbrun", {})
        _runtime = _reported.get("runtimeStats", {})
        _sqft = _runtime.get("sqft", _bbrun.get("sqft"))
        if _sqft is not None:
            if robot_profile_store.update_lifetime_sqft_tracking(float(_sqft)):
                changed = True
    except Exception:  # noqa: BLE001
        # Same reasoning as the coverage baseline above: this reads several
        # optional nested keys off the reported state, so a shape change on
        # the robot's side lands here rather than anywhere visible.
        _LOGGER.debug(
            "Roomba+: lifetime sqft staleness tracking failed", exc_info=True
        )

    if changed:
        await robot_profile_store.async_save(hass, entry.entry_id)


async def _async_bootstrap_umf_aligner(
    hass: HomeAssistant,
    entry: "RoombaConfigEntry",
    coordinator: Any,
) -> None:
    """GS-SMART-UMF — align without local pose data using cloud traversal evidence.

    Two scenarios, both handled here:
      1. No aligner exists yet — the initial construction in __init__.py
         found no points2d/regions at setup time. Attempt to build one now
         from whatever cloud_coordinator.umf_data/regions currently has,
         since a later refresh may have more data than was available at
         startup — this is the actual rescue path the function's name and
         docstring describe.
      2. An aligner exists but isn't aligned yet — refine it in place using
         cloud traversal evidence (unchanged from before).

    Moved from __init__.py to callbacks.py (SETUP-SPLIT Teil B, v3.0.0).

    Bug-hunt fix (v3.5.1, mdarocha field report — i3+ with sparse/early-stage
    UMF data): the call site used to require umf_aligner is not None before
    ever scheduling this task at all — backwards from this function's own
    purpose, since scenario 1 above (no aligner yet) is exactly the
    situation this bootstrap exists to rescue. A robot whose initial UMF
    response lacked points2d/regions would never get a working aligner from
    ANY code path, ever, no matter how much cloud data accumulated
    afterward. That gate is now removed at the call site (see
    make_cloud_refresh_callback below); this function handles aligner is
    None itself instead of bailing out immediately.
    """
    data = entry.runtime_data
    aligner = data.umf_aligner
    gs = data.geometry_store

    if aligner is None:
        if gs is None:
            return
        points2d = coordinator.umf_data.get("points2d")
        umf_regions = coordinator.umf_data.get("regions") or []
        regions = umf_regions or coordinator.regions
        if not points2d or not regions:
            _LOGGER.debug(
                "GS-SMART-UMF: still no points2d/regions for %s — nothing "
                "to bootstrap yet, will check again next refresh.",
                entry.data.get(CONF_BLID, "unknown"),
            )
            return
        from .umf_aligner import UmfAligner
        aligner = UmfAligner(
            points2d=points2d,
            regions=regions,
            geometry_store=gs,
            pmap_version_id=coordinator.umf_data.get("version_id", ""),
        )
        conf = await hass.async_add_executor_job(aligner.align)
        data.umf_aligner = aligner
        _LOGGER.info(
            "GS-SMART-UMF: constructed aligner for %s (points2d/regions "
            "were missing at setup, now available) — confidence=%.2f "
            "aligned=%s",
            entry.data.get(CONF_BLID, "unknown"), conf, aligner.aligned,
        )
        if aligner.aligned:
            return  # good enough already — skip the traversal-evidence path below

    if aligner.aligned:
        return
    if gs is not None and sum(
        1 for m in gs.door_markers if m.mission_count >= 2
    ) >= 2:
        return
    if not coordinator.last_update_success:
        return
    if not getattr(aligner, "_door_candidates", []):
        await hass.async_add_executor_job(aligner.align)

    positions = _extract_traversal_umf_positions(coordinator.raw_records, aligner)

    if not positions:
        blid = entry.data.get(CONF_BLID, "")
        oldest_ts = min(
            (r.get("startTime") for r in coordinator.raw_records if r.get("startTime")),
            default=None,
        )
        if blid and oldest_ts:
            _LOGGER.info(
                "GS-SMART-UMF: fetching older cloud records for %s (before ts=%s)",
                blid, oldest_ts,
            )
            try:
                cloud_api = coordinator.api
                older = await cloud_api.get_mission_history(
                    blid, count=500, before_ts=oldest_ts
                )
                if older:
                    positions = _extract_traversal_umf_positions(older, aligner)
            except Exception as exc:  # noqa: BLE001
                _LOGGER.debug("GS-SMART-UMF: paginated fetch failed — %s", exc)

    if not positions:
        return

    aligner.set_bootstrap_markers(positions)
    conf = await hass.async_add_executor_job(aligner.align)
    _LOGGER.info(
        "GS-SMART-UMF: bootstrap alignment confidence=%.2f aligned=%s for %s",
        conf, aligner.aligned, entry.data.get(CONF_BLID, "unknown"),
    )


_GS_SMART_COVERAGE_MAX_PER_REFRESH = 5

# v3.4.0 GS-SMART-COVERAGE plan §4.1 — which escape_events event types
# count as a genuine "stuck" signal for GridStore.stuck_points.
# start_evade is deliberately excluded: it marks the start of a normal
# obstacle-avoidance manoeuvre (the robot successfully navigating around
# something), not a failure to progress — counting it would mark every
# routine furniture-avoidance as a stuck hotspot.
_GS_SMART_COVERAGE_STUCK_EVENT_TYPES = frozenset({
    "start_stuck", "brush_stall_detected", "wheel_dropped", "stasis_detected",
})


def _gs_coverage_safe_int(value: Any) -> int | None:
    if value is None:
        return None
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


def _gs_coverage_mission_start_weekday_hour(started_at: Any) -> tuple[int, int] | None:
    """Mirror image.py's live-path stuck_wh derivation exactly: ONE
    (weekday, hour) per mission, from the mission's own start
    timestamp — not per stuck event. escape_events entries carry no
    individual timestamps, so this is not just convenient but the only
    option; it also matches the existing live-path semantics rather
    than inventing a different one for the cloud path."""
    if not started_at:
        return None
    try:
        parsed = dt_util.parse_datetime(started_at)
        if parsed is None:
            return None
        local = dt_util.as_local(parsed)
        return (local.weekday(), local.hour)
    except Exception:  # noqa: BLE001
        return None


def _gs_coverage_umf_points_to_pose(
    coverage_mm: list[Any], aligner: Any
) -> list[tuple[float, float]]:
    """Convert UMF-space mm points (already unit-converted by
    mission_map.py's _points_to_mm()) to pose-space via the aligner.
    Points umf_to_pose() can't resolve are skipped, not fatal — the
    same per-point defensive posture as _points_to_mm() itself.

    v3.4.0 bug-hunt fix: a non-numeric coordinate used to reach
    aligner.umf_to_pose() unfiltered and crash there (real
    UmfAligner.umf_to_pose() does cos_r * x_umf arithmetic — a str
    raises TypeError, not caught anywhere in this loop or its caller).
    float() conversion here catches it per-point, same as
    _points_to_mm()'s own guard.
    """
    out: list[tuple[float, float]] = []
    for p in coverage_mm:
        if not isinstance(p, (list, tuple)) or len(p) < 2:
            continue
        try:
            x, y = float(p[0]), float(p[1])
        except (TypeError, ValueError):
            continue
        converted = aligner.umf_to_pose(x, y)
        if converted is not None:
            out.append(converted)
    return out


def _gs_coverage_classify_stuck_events(
    escape_events: list[Any], aligner: Any
) -> list[tuple[float, float]]:
    """Filter escape_events to the "stuck" subset (see
    _GS_SMART_COVERAGE_STUCK_EVENT_TYPES above) and convert their UMF
    poses to pose-space. An event type outside the known 5 is logged
    (not silently dropped) so a real future occurrence is diagnosable
    instead of invisible — same posture as mission_map.py's shape
    warning for this same layer.

    v3.4.0 bug-hunt fix: same non-numeric-coordinate crash risk as
    _gs_coverage_umf_points_to_pose() above — escape_events poses get
    NO type validation anywhere upstream (unlike the coverage layer,
    which goes through _points_to_mm()'s guard), so this is the first
    and only place that can catch it.
    """
    out: list[tuple[float, float]] = []
    for ev in escape_events:
        if not isinstance(ev, dict):
            continue
        event_type = ev.get("event")
        if event_type not in _GS_SMART_COVERAGE_STUCK_EVENT_TYPES:
            if event_type not in (None, "start_evade"):
                _LOGGER.info(
                    "GS-SMART-COVERAGE: unclassified escape_event type "
                    "%r — not counted as stuck; add it to "
                    "_GS_SMART_COVERAGE_STUCK_EVENT_TYPES if it should be",
                    event_type,
                )
            continue
        pose = ev.get("pose")
        if not isinstance(pose, (list, tuple)) or len(pose) < 2:
            continue
        try:
            x, y = float(pose[0]), float(pose[1])
        except (TypeError, ValueError):
            continue
        converted = aligner.umf_to_pose(x, y)
        if converted is not None:
            out.append(converted)
    return out


async def _async_update_gs_smart_coverage(
    hass: HomeAssistant,
    entry: "RoombaConfigEntry",
    cloud_coordinator: Any,
) -> None:
    """v3.4.0 GS-SMART-COVERAGE — cloud-derived GridStore backfill for
    pose-less SMART robots (lewis firmware, which reports the pose
    capability flag but doesn't stream live pose during missions —
    see the plan's §2 for the full analysis). Structural precedent:
    _async_bootstrap_umf_aligner() above.

    Reuses async_fetch_mission_map() (built in v3.3.0 exactly for this
    reuse — see mission_map.py's docstring). Shares a single watermark
    (GridStore.last_processed_nmssn) with the live path (image.py) so
    a mission already fed via real local pose is never double-counted
    here — whichever path processes a mission first claims it.

    cloud_coordinator is accepted (matching every other check on this
    hook's signature) but unused directly — data.cloud_coordinator via
    async_fetch_mission_map() is the actual cloud access path.
    """
    data = entry.runtime_data
    gs = data.grid_store
    aligner = data.umf_aligner
    ms = data.mission_store
    if gs is None or ms is None or aligner is None or not aligner.aligned:
        return

    watermark = gs.last_processed_nmssn
    candidates = [
        # `records` IS A PROPERTY, and this was the one place calling it.
        # `ms.records()` raises TypeError -- a Sequence is not callable --
        # so this whole coverage pass died on its first line every time
        # it ran. Four other call sites in the integration read it
        # correctly; this one did not, and nothing exercised it.
        r for r in ms.records
        if r.get("pmaps_info")
        and (_gs_coverage_safe_int(r.get("nMssn")) or 0) > watermark
    ]
    candidates.sort(key=lambda r: _gs_coverage_safe_int(r.get("nMssn")) or 0)
    # Rate-cap (plan §4.2): a robot with a large backlog (first
    # activation, or HA offline for a while) catches up gradually over
    # several refresh cycles rather than bursting one cloud call per
    # backlog mission in a single cycle.
    candidates = candidates[:_GS_SMART_COVERAGE_MAX_PER_REFRESH]

    changed = False
    for record in candidates:
        record_nmssn = _gs_coverage_safe_int(record.get("nMssn"))
        try:
            payload = await async_fetch_mission_map(data, record)
        except (MissionMapUnavailable, MissionMapMismatch) as exc:
            _LOGGER.debug(
                "GS-SMART-COVERAGE: skipping nMssn=%s — %s",
                record_nmssn, exc,
            )
            # A structurally-known-bad record (no coverage layer, or a
            # verify-gate mismatch) will never succeed on retry —
            # advance the watermark so it isn't retried every refresh.
            gs.record_processed_nmssn(record_nmssn)
            changed = True
            continue
        except Exception as exc:  # noqa: BLE001 — one bad mission must not abort the batch
            _LOGGER.warning(
                "GS-SMART-COVERAGE: fetch failed for nMssn=%s — %s",
                record_nmssn, exc,
            )
            continue  # watermark NOT advanced — retried on the next refresh

        pose_points = _gs_coverage_umf_points_to_pose(
            payload["coverage_mm"], aligner,
        )
        stuck_points = _gs_coverage_classify_stuck_events(
            payload.get("escape_events", []), aligner,
        )
        stuck_wh = _gs_coverage_mission_start_weekday_hour(
            record.get("started_at")
        )

        gs.update_from_mission(
            pose_points, stuck_points,
            stuck_wh=stuck_wh,
            robot_radius_mm=ROBOT_DIAMETER_MM_ISJ_SERIES / 2,
        )
        gs.record_processed_nmssn(record_nmssn)
        changed = True

    if changed:
        await gs.async_save(hass, entry.entry_id)


def make_cloud_refresh_callback(
    hass: HomeAssistant,
    config_entry: "RoombaConfigEntry",
    cloud_coordinator: Any,
) -> Any:
    """Factory: return the @callback for cloud coordinator listener registration.

    SETUP-SPLIT Teil B (v3.0.0) — extracted from async_setup_entry in __init__.py.
    """
    @callback
    def _on_cloud_refresh_complete() -> None:
        from .repairs import async_check_cloud_stale
        config_entry.async_create_task(
            hass, async_check_cloud_stale(hass, config_entry, cloud_coordinator), name='roomba_plus_cloud_stale_check'
        )
        if not cloud_coordinator.last_update_success:
            return
        ms = config_entry.runtime_data.mission_store
        if ms is None:
            return
        _bf = ms.backfill_from_cloud(cloud_coordinator.raw_records)
        if _bf.corrected or _bf.enriched:
            config_entry.async_create_task(
                hass, ms.async_save(hass, config_entry.entry_id), name='roomba_plus_cloud_merge_save'
            )
        _dtm = config_entry.runtime_data.dirt_threshold_manager
        if _dtm is not None:
            config_entry.async_create_task(
                hass, _dtm.async_evaluate(cloud_coordinator, config_entry.entry_id), name='roomba_plus_demand_clean_eval'
            )
        if _umf_version_changed(cloud_coordinator, config_entry):
            config_entry.async_create_task(
                hass, _async_realign(hass, config_entry, cloud_coordinator), name='roomba_plus_umf_realign'
            )
        from .repairs import async_check_error_recurrence
        config_entry.async_create_task(
            hass, async_check_error_recurrence(hass, config_entry), name='roomba_plus_error_recurrence_check'
        )
        from .repairs import async_check_cancellation_recurrence
        config_entry.async_create_task(
            hass, async_check_cancellation_recurrence(hass, config_entry), name='roomba_plus_cancellation_recurrence_check'
        )
        _rps = config_entry.runtime_data.robot_profile_store
        if _rps is not None:
            config_entry.async_create_task(
                hass, _async_update_robot_profile_store(hass, config_entry, ms, _rps), name='roomba_plus_profile_store_update'
            )
        if config_entry.runtime_data.grid_store is not None:
            from .repairs import async_check_stuck_pattern
            config_entry.async_create_task(
                hass, async_check_stuck_pattern(hass, config_entry), name='roomba_plus_l7_stuck_pattern_check'
            )
        # v3.4.0 GS-SMART-COVERAGE — must run BEFORE the GridStore-reading
        # FURNITURE check below so a mission backfilled from the cloud in
        # THIS refresh cycle is already reflected when that check runs, not
        # only from the next cycle onward. umf_aligner is required here
        # (unlike GS-SMART-UMF's bootstrap gate further below, fixed in
        # v3.5.1 to no longer require it) because this function actually
        # needs a working aligner to transform poses — it has no bootstrap
        # path of its own, so there's nothing useful it can do without one.
        # The function itself no-ops cleanly if the aligner isn't aligned
        # yet or there's nothing new to backfill.
        from .models import MapCapability
        if (
            config_entry.runtime_data.map_capability == MapCapability.SMART
            and config_entry.runtime_data.grid_store is not None
            and config_entry.runtime_data.umf_aligner is not None
        ):
            config_entry.async_create_task(
                hass, _async_update_gs_smart_coverage(hass, config_entry, cloud_coordinator), name='roomba_plus_gs_smart_coverage'
            )
        # FURNITURE (layout-change) check dispatched on cloud-refresh
        # cadence. The former ROOM-ACCESS, STUCK-HOTSPOT, COVERAGE-FREQ
        # and CROSS-CORR checks were removed in v3.5.0 (Repairs redesign):
        # ROOM-ACCESS/STUCK-HOTSPOT data is already exposed via the
        # ?format=hazards endpoint + map, COVERAGE-FREQ was a derivable
        # nudge, and CROSS-CORR is already surfaced by the
        # dirt_weather_correlation sensor.
        if config_entry.runtime_data.grid_store is not None:
            from .repairs import async_check_furniture_change
            config_entry.async_create_task(
                hass, async_check_furniture_change(hass, config_entry), name='roomba_plus_furniture_change_check'
            )
        # v3.5.0 Repairs redesign — the standalone smberr_high Repair was
        # removed; its signal now feeds as corroborating context into
        # dock_contact_health and battery_contact_suspect (see
        # async_check_dock_health / async_check_battery_contact_issue) —
        # the raw bbchg.smberr count still appears in diagnostics.
        from .repairs import async_check_dock_health
        config_entry.async_create_task(
            hass, async_check_dock_health(hass, config_entry), name='roomba_plus_dock_health_check'
        )
        from .models import MapCapability
        if config_entry.runtime_data.map_capability == MapCapability.SMART:
            # v3.5.1 bug-hunt fix (mdarocha field report): this used to also
            # require umf_aligner is not None, which meant a robot whose
            # initial UMF response lacked points2d/regions at setup would
            # NEVER get this task scheduled at all, ever — backwards from
            # this bootstrap's whole purpose (see
            # _async_bootstrap_umf_aligner's docstring). The function itself
            # now handles constructing a fresh aligner when one doesn't
            # exist yet, so this only needs to gate on map_capability.
            config_entry.async_create_task(
                hass, _async_bootstrap_umf_aligner(hass, config_entry, cloud_coordinator), name='roomba_plus_gs_smart_umf_bootstrap'
            )

    return _on_cloud_refresh_complete
