from homeassistant.util import dt as dt_util

_LOGGER = logging.getLogger(__name__)

STORAGE_KEY_PREFIX = "roomba_plus_maintenance"
STORAGE_VERSION    = 1

#: Application payload version, separate from STORAGE_VERSION above.
#: STORAGE_VERSION is Home Assistant's own and must stay pinned at 1
#: forever -- raising it hands the file to HA's migration machinery,
#: which raises NotImplementedError unless we implement its hook.
#:
#: This one is ours. Nothing branches on it yet; it is recorded so a
#: future format change can be RECOGNISED instead of silently misread.
#: This store holds when the user replaced a part, which cannot be
#: rebuilt from anything -- unlike the pose-derived stores, which just
#: refuse to load an unknown version and fill again on the next mission.
PAYLOAD_VERSION    = 1

#: How many "marked done" records the store keeps (4.5.0).
MAINTENANCE_LOG_SIZE = 30

#: The shortest gap between two resets that is learned as a part's life,
#: as a share of its series interval (4.5.4, `_learned_hours`).
LEARNED_MIN_SHARE = 0.25


def _parse(value: Any) -> datetime | None:
    """An ISO timestamp from the store as an aware datetime, or None."""
    if not isinstance(value, str) or not value:
        return None
    parsed = dt_util.parse_datetime(value)
    if parsed is None:
        return None
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=dt_util.DEFAULT_TIME_ZONE)
    return parsed


def _iso_from_epoch(ts: Any) -> str | None:
    """Convert an epoch-seconds reset timestamp to a local ISO-8601 string.

    iRobot's parts endpoint reports `last_updated_ts` in epoch seconds, and
    omits it entirely for a part that has never been reset. Returns None for
    that case and for any unparseable value, so a missing timestamp leaves
    the store's existing value untouched instead of blanking it.
    """
    if ts is None:
        return None
    try:
        epoch = int(ts)
    except (TypeError, ValueError):
        return None
    if epoch <= 0:
        return None
    return dt_util.utc_from_timestamp(epoch).astimezone(dt_util.DEFAULT_TIME_ZONE).isoformat()


@dataclass
class MaintenanceStore:
    """Stores the bbrun.hr value and wall-clock time at each part reset.

    All _hr values in hours (integer, matching bbrun.hr).
    All _reset_at values are ISO-8601 strings or None (pre-v1.7 installs).
    Default 0 / None = never reset.
    """

    # Reset reference points (hours)
    filter_reset_hr: int = 0
    brush_reset_hr: int  = 0
    battery_reset_hr: int = 0

    # Wall-clock timestamps — None until first reset after v1.7.0
    # Surfaces as HA state "unknown" until then, which is correct.
    filter_reset_at: str | None = None
    brush_reset_at: str | None = None
    battery_reset_at: str | None = None

    # F5d — baseline estCap (mAh) recorded on first observation.
    # Used to compute battery_capacity_retention as pct of original capacity.
    # None until the first MQTT message containing bbchg3.estCap is processed.
    baseline_estcap: float | None = None

    # F6g — consecutive scheduled clean opportunities missed (blocked or skipped).
    # Incremented by BlockingManager on timeout; reset to 0 on any completed mission.
    consecutive_skips: int = 0

    # L2 — replacement history for self-calibrating lifespan (v2.5.0).
    filter_reset_history: list[int] = field(default_factory=list)
    brush_reset_history: list[int] = field(default_factory=list)

    # v3.4.1 MAINTENANCE-COLD-START — tracks whether filter_reset_hr/
    # brush_reset_hr have already been auto-seeded to the robot's runtime
    # hours on first-ever load (see __init__.py's async setup). Distinct
    # from filter_reset_history/brush_reset_history, which only ever
    # records REAL user-confirmed resets — this flag exists specifically
    # so the auto-seed step fires exactly once per robot, not on every
    # restart, without polluting the learned-wear-rate history with a
    # synthetic, non-user-confirmed "reset" event.
    filter_baseline_seeded: bool = False
    brush_baseline_seeded: bool = False

    # side_brush/clean_base_bag mirror the filter/brush slots above.
    #
    # THESE USED TO BE CALLED "cloud-only roles ... never auto-seeded (no
    # CONF_*_HOURS default exists to seed against)". The parenthetical
    # was false: DEFAULT_SIDE_BRUSH_HOURS (150) and the bag's default
    # (30) both exist and `threshold_hours()` already falls back to
    # them.
    #
    # On an account that does not serve parts, the hydration leg never
    # fires, so the baseline stayed 0 forever and `maintenance_due`
    # reported the robot's whole lifetime as overdue -- with no reset
    # service for these two roles and a reset button that is only built
    # when the cloud serves the part, there was no way out from inside
    # Home Assistant (@azrael-129, a 980 at 2252 h).
    #
    # They are seeded at cold start now, like filter and brush, and the
    # seed yields to cloud truth on the first successful hydration.
    side_brush_reset_hr: int = 0
    side_brush_reset_at: str | None = None
    side_brush_reset_history: list[int] = field(default_factory=list)
    side_brush_baseline_seeded: bool = False

    clean_base_bag_reset_hr: int = 0
    clean_base_bag_reset_at: str | None = None
    clean_base_bag_reset_history: list[int] = field(default_factory=list)
    clean_base_bag_baseline_seeded: bool = False

    # Cloud consumable state, keyed by iRobot `part_id`. Written by
    # hydrate_from_cloud_parts() from /v1/robots/{blid}/parts and read by
    # the per-part cloud sensors. Held here rather than only in the
    # coordinator so the last known values survive a cloud outage and an
    # HA restart, matching how every other maintenance figure behaves.
    cloud_parts: dict[str, dict[str, Any]] = field(default_factory=dict)
    cloud_parts_hydrated_at: str | None = None

    # IA74-MAINT (v2.6.0) — clean/inspect timestamps (calendar-based, no bbrun.hr)
    wheel_cleaned_at: str | None = None
    contact_cleaned_at: str | None = None
    bin_cleaned_at: str | None = None

    # 4.3.2 care reminders -- the cleaning counterparts of the replacement
    # slots above, and the other half of CARE_TASKS next to wheel and
    # contact. `care_since` is when reminders began: a task never marked
    # done counts from there. Without it an upgrade would show every task
    # overdue at once, and filling the `*_cleaned_at` fields in instead
    # would make the "last cleaned" sensors claim a cleaning nobody did.
    filter_cleaned_at: str | None = None
    brushes_cleaned_at: str | None = None
    side_brush_cleaned_at: str | None = None
    cliff_sensors_cleaned_at: str | None = None
    care_since: str | None = None

    # 4.3.2 -- the robot's series intervals from ROBOT_PROFILES, by role
    # (maintenance_profile_hours). Set at setup from the SKU, or when a
    # late SKU arrives; never persisted, since the SKU decides it anew.
    profile_hours: dict[str, int] = field(default_factory=dict)

    # 4.5.0 -- the robot's hour meter when the cloud counters were last
    # read. A counter is minutes used AT THAT MOMENT; the hours run
    # since then are added to it, so the figure stays live between
    # polls instead of standing still until the next one.
    cloud_parts_hydrated_hr: int | None = None

    # 4.5.4 -- the robot's hour meter as last seen, kept across restarts
    # (`hours()`). A 600 does not send its hours again after Home
    # Assistant reconnects; until its next mission every part read as
    # new (@tankdeer).
    last_known_hr: int = 0

    # 4.5.0 -- per maintenance entry (maintenance_model.py), keyed by its
    # id: `due_since` (when it was first seen due; "overdue" counts from
    # there), `snoozed_until`, and `notified` (the level last announced,
    # so a restart does not announce it again).
    maintenance_state: dict[str, dict[str, Any]] = field(default_factory=dict)
    # 4.5.0 -- what was marked done, when and from where; newest last,
    # at most MAINTENANCE_LOG_SIZE entries.
    maintenance_log: list[dict[str, Any]] = field(default_factory=list)

    async def async_load(self, hass: HomeAssistant, entry_id: str) -> None:
        """Load persisted reset values from hass.storage."""
        store: Store[dict[str, Any]] = Store(hass, STORAGE_VERSION, f"{STORAGE_KEY_PREFIX}_{entry_id}")
        data: dict[str, Any] | None = await store.async_load()
        if not data:
            _LOGGER.debug("MaintenanceStore: no persisted data for %s", entry_id)
            return
        # A payload written by a NEWER release than this one. Absent means
        # version 1: every file written before this field existed is in
        # the current format, so a missing key must not be read as a
        # mismatch -- that would discard the replacement dates of every
        # install that upgrades.
        stored_version = int(data.get("payload_version", 1) or 1)
        if stored_version > PAYLOAD_VERSION:
            _LOGGER.warning(
                "MaintenanceStore: stored payload is version %d, this "
                "release understands %d. Not loading it — maintenance "
                "counters will start from zero rather than be read "
                "wrongly. Downgrading? The file is intact; a newer "
                "release will read it again.",
                stored_version, PAYLOAD_VERSION,
            )
            return
        try:
            self.filter_reset_hr  = int(data.get("filter_reset_hr",  0))
            self.brush_reset_hr   = int(data.get("brush_reset_hr",   0))
            self.battery_reset_hr = int(data.get("battery_reset_hr", 0))
            # New in v1.7.0 — None for pre-upgrade installs (backward compat)
            self.filter_reset_at  = data.get("filter_reset_at")
            self.brush_reset_at   = data.get("brush_reset_at")
            self.battery_reset_at = data.get("battery_reset_at")
            # F5d — None until first estCap observation (v2.1+)
            raw_estcap = data.get("baseline_estcap")
            self.baseline_estcap = float(raw_estcap) if raw_estcap is not None else None
            # F6g — 0 for pre-v2.1 installs
            self.consecutive_skips = int(data.get("consecutive_skips", 0))
            # L2: restore replacement history (empty list for pre-v2.5 installs)
            self.filter_reset_history = [
                int(h) for h in data.get("filter_reset_history", [])
            ]
            self.brush_reset_history = [
                int(h) for h in data.get("brush_reset_history", [])
            ]
            # v3.4.1 MAINTENANCE-COLD-START — False for pre-v3.4.1 installs
            # (backward compat: treated as "not yet seeded", matching a
            # fresh store — correct, since this flag didn't exist before
            # and no seeding could have happened yet).
            self.filter_baseline_seeded = bool(data.get("filter_baseline_seeded", False))
            self.brush_baseline_seeded  = bool(data.get("brush_baseline_seeded",  False))
            self.side_brush_reset_hr = int(data.get("side_brush_reset_hr", 0))
            self.side_brush_reset_at = data.get("side_brush_reset_at")
            self.side_brush_reset_history = [
                int(h) for h in data.get("side_brush_reset_history", [])
            ]
            self.side_brush_baseline_seeded = bool(data.get("side_brush_baseline_seeded", False))
            self.clean_base_bag_reset_hr = int(data.get("clean_base_bag_reset_hr", 0))
            self.clean_base_bag_reset_at = data.get("clean_base_bag_reset_at")
            self.clean_base_bag_reset_history = [
                int(h) for h in data.get("clean_base_bag_reset_history", [])
            ]
            self.clean_base_bag_baseline_seeded = bool(data.get("clean_base_bag_baseline_seeded", False))
            # Cloud consumable state — absent on installs that predate
            # cloud parts hydration, and absent for robots whose account
            # does not serve the endpoint. Both are "no cloud truth yet".
            raw_cloud_parts = data.get("cloud_parts")
            self.cloud_parts = (
                {str(k): dict(v) for k, v in raw_cloud_parts.items() if isinstance(v, Mapping)}
                if isinstance(raw_cloud_parts, Mapping) else {}
            )
            self.cloud_parts_hydrated_at = data.get("cloud_parts_hydrated_at")
            # IA74-MAINT: calendar-based inspect timestamps
            self.wheel_cleaned_at   = data.get("wheel_cleaned_at")
            self.contact_cleaned_at = data.get("contact_cleaned_at")
            self.bin_cleaned_at     = data.get("bin_cleaned_at")
            self.filter_cleaned_at = data.get("filter_cleaned_at")
            self.brushes_cleaned_at = data.get("brushes_cleaned_at")
            self.side_brush_cleaned_at = data.get("side_brush_cleaned_at")
            self.cliff_sensors_cleaned_at = data.get("cliff_sensors_cleaned_at")
            self.care_since = data.get("care_since")
            raw_hr = data.get("cloud_parts_hydrated_hr")
            self.cloud_parts_hydrated_hr = int(raw_hr) if raw_hr is not None else None
            self.last_known_hr = int(data.get("last_known_hr") or 0)
            raw_state = data.get("maintenance_state")
            self.maintenance_state = (
                {str(k): dict(v) for k, v in raw_state.items() if isinstance(v, Mapping)}
                if isinstance(raw_state, Mapping) else {}
            )
            raw_log = data.get("maintenance_log")
            self.maintenance_log = [
                dict(e) for e in raw_log if isinstance(e, Mapping)
            ][-MAINTENANCE_LOG_SIZE:] if isinstance(raw_log, list) else []
            _LOGGER.debug(
                "MaintenanceStore: loaded — filter_reset=%dh brush_reset=%dh",
                self.filter_reset_hr, self.brush_reset_hr,
            )
        except (TypeError, ValueError) as exc:
            _LOGGER.warning("MaintenanceStore: failed to load data: %s", exc)

