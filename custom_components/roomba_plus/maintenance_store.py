    def seed_care(self, enabled: bool = True) -> bool:
        """Start or stop the care reminders. True when it changed the store.

        Runs at every setup. Switched on, it sets `care_since` once:
        reminders count from the moment they exist, not from a cleaning
        nobody recorded. Switched off, it clears it, so switching on
        again months later starts afresh instead of opening with every
        task overdue. Recorded cleanings are kept either way -- they
        are facts, and the "last cleaned" sensors show them.
        """
        if not enabled:
            if self.care_since is None:
                return False
            self.care_since = None
            return True
        if self.care_since is not None:
            return False
        self.care_since = dt_util.now().isoformat()
        return True

    def care_due(
        self, task: CareTask, pets: bool, prime: bool = False,
    ) -> datetime | None:
        """When this task is next due, or None before reminders started.

        Counts from the later of the last recorded cleaning and
        `care_since`. A cleaning recorded before the reminders started
        -- the wheels, cleaned in 2024 through a button that exists
        since 2.7 -- must not make that task overdue on the first day.
        A timestamp that does not parse counts as not recorded.
        """
        since = _parse(self.care_since)
        if since is None:
            return None
        cleaned = _parse(getattr(self, f"{task.slot}_cleaned_at"))
        start = max(since, cleaned) if cleaned is not None else since
        return start + timedelta(days=task.interval_days(pets, prime))

    def care_schedule(
        self, braava: bool, pets: bool, now: datetime | None = None,
    ) -> list[dict[str, Any]]:
        """Every care task this robot has, earliest due first.

        Each entry: `task`, `last_done` (ISO or None), `due` (ISO),
        `interval_days`, `overdue`. Empty before `seed_care` ran.
        """
        now = now or dt_util.now()
        rows: list[tuple[datetime, dict[str, Any]]] = []
        for task in CARE_TASKS:
            if braava and not task.braava:
                continue
            due = self.care_due(task, pets)
            if due is None:
                continue
            rows.append((due, {
                "task": task.slot,
                "last_done": getattr(self, f"{task.slot}_cleaned_at"),
                "due": due.isoformat(),
                "interval_days": task.days_with_pets if pets else task.days,
                "overdue": due <= now,
            }))
        rows.sort(key=lambda r: r[0])
        return [row for _, row in rows]

    # ── F5d — Battery capacity baseline ──────────────────────────────────────

    def record_estcap_if_needed(self, estcap_mah: float) -> bool:
        """Record converted mAh capacity as baseline on first valid observation.

        F5d — called by battery_capacity_retention sensor on every MQTT update.
        Receives the *converted* mAh value (raw estCap ÷ chemistry scale),
        NOT the raw BMS value.  Only sets the baseline once; subsequent calls
        are no-ops so the baseline never drifts once established.

        Returns True when the baseline was just set for the first time so the
        caller can schedule async_save() to persist the value immediately.
        """
        if self.baseline_estcap is None and estcap_mah > 0:
            self.baseline_estcap = float(estcap_mah)
            _LOGGER.info(
                "MaintenanceStore: baseline_estcap set to %.0f mAh "
                "(converted from raw BMS value)", estcap_mah
            )
            return True
        return False

    # ── L2 — Self-calibrating lifespan ───────────────────────────────────────

    def _learned_hours(self, slot: str) -> float | None:
        """Median interval between a role's local resets, or None when no
        usable interval has been recorded. Shared by the local-threshold
        fallback and `max_hours`.

        AN INTERVAL THAT STARTS AT A RESET RECORDED AT 0 HOURS IS NOT A
        LIFESPAN. Until 4.3.0 the reset buttons read `bbrun.hr`, which a
        j7+/j9+ does not carry, so every reset there was recorded at 0.
        The first correct reset after the update then made an "interval"
        of the robot's whole lifetime: @msva17's filter, edge brush and bag
        all learned 1556 h, and showed it as both remaining and
        `max_hours`. With two resets that one interval is the whole median.

        Read-side, on purpose: it corrects histories already stored on
        every affected install without rewriting them, and it holds for a
        reset recorded at 0 because the hours were not known yet. The cost
        is one interval on a robot whose part was really replaced at hour
        0; learning there starts one replacement later, on the configured
        threshold until then.

        NOR IS ONE SHORTER THAN A QUARTER OF THE SERIES INTERVAL (4.5.4,
        @rodelero1). Resets an hour apart -- a second press, a test --
        taught an i7's filter a life of 1 h. The new filter read due
        after 4 h, he replaced it, and that reset made the median 2.5 h:
        2 h left on a filter fitted that day, due again soon after, each
        early replacement teaching the next. A part swapped that early
        was not worn out, so the interval says nothing about its life.
        Read-side too, so stored histories are corrected without a
        rewrite. The bound is the series interval or the global default,
        not an hour option, so configuring one does not move it: 13 h
        for a 52 h filter.
        """
        history = getattr(self, f"{slot}_reset_history")
        shortest = self._expected_hours(slot) * LEARNED_MIN_SHARE
        intervals = [
            end - start
            for start, end in zip(history, history[1:])
            if start > 0 and end > start and end - start >= shortest
        ]
        return statistics.median(intervals) if intervals else None

    def _expected_hours(self, slot: str) -> float:
        """A slot's interval before any learning: the series profile,
        else the global default."""
        for role, spec in CONSUMABLE_ROLES.items():
            if spec.slot == slot:
                return float(self.profile_hours.get(role, spec.default_hours))
        return 0.0

    def forget_learned(self, role: str) -> bool:
        """Forget a role's learned replacement interval (4.5.0, @msva17).

        A learned interval can be wrong for reasons the read-side filter
        cannot see -- a reset pressed by mistake, a part swapped early --
        and the only way back was editing the storage file. This clears
        the replacement history the interval is learned from; the current
        part's baseline stays, so nothing else moves. Learning starts again
        with the next two replacements. True when there was anything.
        """
        history = getattr(self, f"{CONSUMABLE_ROLES[role].slot}_reset_history")
        if not history:
            return False
        history.clear()
        return True

    def learned_hours(self, role: str) -> float | None:
        """Return the learned replacement interval for a consumable role."""
        return self._learned_hours(CONSUMABLE_ROLES[role].slot)

    @property
    def learned_filter_hours(self) -> float | None:
        """Median interval between filter replacements, or None if < 2 resets."""
        return self.learned_hours("filter")

    @property
    def learned_brush_hours(self) -> float | None:
        """Median interval between brush replacements, or None if < 2 resets."""
        return self.learned_hours("main_brush")

    # ── Remaining-life calculations ───────────────────────────────────────────

    def interval_source(self, role: str, options: Mapping[str, Any]) -> str:
        """Where a role's interval comes from, best first (4.3.2):
        `cloud` (iRobot's counter for this robot), `learned` (this
        household's own resets), `configured` (an hour option set by
        hand), `profile` (the robot's series in ROBOT_PROFILES) or
        `irobot_budget` (the last fallback, iRobot's budget read off an
        i3+ -- see DEFAULT_FILTER_HOURS)."""
        return self.interval_hours(role, options)[1]

    def threshold_hours(self, role: str, options: Mapping[str, Any]) -> int:
        """A role's local threshold: the hour option, else the robot's
        series profile, else the global default."""
        spec = CONSUMABLE_ROLES[role]
        fallback = self.profile_hours.get(role, spec.default_hours)
        if spec.conf_key is None or spec.conf_key not in options:
            return fallback
        try:
            return int(options[spec.conf_key])
        except (TypeError, ValueError):
            return fallback

    def due_items(
        self, vacuum_state: Mapping[str, Any], options: Mapping[str, Any]
    ) -> list[str]:
        """Return due consumables using the shared four-role lifecycle."""
        current_hr = lifetime_hours(vacuum_state)
        is_mop_device = is_mop(dict(vacuum_state))
        items: list[str] = []
        for role, spec in CONSUMABLE_ROLES.items():
            # SKIP PARTS THE ROBOT DOES NOT HAVE.
            #
            # A 900-series charges on a plain dock, so it has no Clean
            # Base bag. Every per-part entity was already suppressed for
            # it, but this path iterated all four roles regardless -- so
            # a Roomba 980 reported the bag due once runtime passed the
            # 30-hour default, for a bag that does not exist
            # (a tester's R980020: `dock: {"known": false}`, bbrun.hr 105,
            # reported 75 hours overdue).
            #
            # The cloud never contradicted it because there is no cloud
            # record for a part the robot does not have, and
            # `_is_due()` then falls through to the local hour count --
            # which counts runtime, not bag use.
            if spec.absent_when is not None and spec.absent_when(dict(vacuum_state)):
                continue
            threshold = self.threshold_hours(role, options)
            if self._is_due(role, current_hr, threshold):
                items.append(
                    spec.mop_due_key
                    if spec.mop_due_key and is_mop_device else spec.due_key
                )
        return items

    def _is_due(self, role: str, current_hr: int, threshold: int) -> bool:
        """True when a maintenance role is due for replacement.

        The same rule as the maintenance model's (4.5.0): the part has
        served its interval. With a cloud counter that is the counter
        run out, at minute precision -- and it follows the hours run
        since the counter was read, and a replacement recorded here
        since, where until 4.5.0 a reset button left the robot due
        until the next restart re-read the cloud. `threshold` is the
        local threshold for a robot without a counter.
        """
        current_hr = self.hours(current_hr)
        live = self._live_cloud_minutes(role, current_hr)
        if live is not None:
            return live[1] <= 0
        return self.remaining_hours(role, current_hr, threshold) == 0

    def _local_remaining(self, slot: str, current_hr: int, threshold: int) -> int:
        """Hours remaining until replacement per the local reset slot alone,
        ignoring any cloud counter. Uses the learned interval once 2+
        resets have been recorded, else the given threshold. round(), not
        int(), avoids a systematic truncation error of up to 59 minutes.
        """
        effective = round(self._learned_hours(slot) or threshold)
        try:
            reset_hr = int(getattr(self, f"{slot}_reset_hr"))
        except (TypeError, ValueError):
            return effective
        return max(0, effective - (current_hr - reset_hr))

    def remaining_hours(self, role: str, current_hr: int, threshold: int) -> int:
        """Hours remaining until replacement for any of the four
        maintenance roles, local-only (no cloud counter) — see
        _local_remaining()."""
        return self._local_remaining(
            CONSUMABLE_ROLES[role].slot, self.hours(current_hr), threshold
        )

    def filter_remaining(self, current_hr: int, threshold: int) -> int:
        """Hours remaining until next filter replacement, local-only (no
        cloud counter) — see _local_remaining()."""
        return self.remaining_hours("filter", current_hr, threshold)

    def brush_remaining(self, current_hr: int, threshold: int) -> int:
        """Hours remaining until next brush/pad replacement, local-only (no
        cloud counter) — see _local_remaining()."""
        return self.remaining_hours("main_brush", current_hr, threshold)
