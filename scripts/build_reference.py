RESPONSE = {
    "none": "",
    "optional": "Optional",
    "only": "Always",
}


def action_responses() -> dict[str, str]:
    """{action: none|optional|only}, from the registration itself."""
    sys.path.insert(0, str(ROOT))
    from custom_components.roomba_plus import services  # noqa: PLC0415

    hass = MagicMock()
    hass.services.has_service.return_value = False
    services.async_register_services(hass)
    out: dict[str, str] = {}
    for call in hass.services.async_register.call_args_list:
        response = call.kwargs.get("supports_response")
        out[call.args[1]] = str(response.value) if response is not None else "none"
    return out


def actions_page() -> str:
    described = yaml.safe_load((CC / "services.yaml").read_text(encoding="utf-8"))
    texts = _strings()["services"]
    responses = action_responses()
    lines = [HEADER.format(title="Actions")]
    lines.append(
        "Every action Roomba+ adds, as the action editor shows it "
        "(**Developer tools → Actions**, or an automation's *Add action*). "
        "Most act on one robot: pick its vacuum entity as the target, or "
        "give `entity_id`. *Returns data* says whether the action answers "
        "with a response you can use in a script (`response_variable`).\n\n"
        "Which robots each action works on, and examples: "
        "[Scripts and Assist](../guides/scripts-and-assist.md#which-robots-each-action-works-on), "
        "[Clean rooms and zones](../guides/clean-rooms.md), "
        "[Automations](../AUTOMATIONS.md).\n\n"
    )
    lines.append("| Action | What it does | Returns data |\n|---|---|---|\n")
    def text_of(name: str) -> dict[str, Any]:
        """What the action editor shows: the translation, else services.yaml."""
        spec = described[name] or {}
        text = texts.get(name, {})
        fields = {
            field: {
                "name": (text.get("fields") or {}).get(field, {}).get("name")
                or (fspec or {}).get("name") or field,
                "description": (text.get("fields") or {}).get(field, {}).get("description")
                or (fspec or {}).get("description") or "",
            }
            for field, fspec in (spec.get("fields") or {}).items()
        }
        return {
            "name": text.get("name") or spec.get("name") or name,
            "description": text.get("description") or spec.get("description") or "",
            "fields": fields,
        }

    for name in sorted(described):
        text = text_of(name)
        lines.append(
            f"| [`roomba_plus.{name}`](#roomba_plus{name}) | {_cell(_first_sentence(text['description']))} "
            f"| {RESPONSE.get(responses.get(name, 'none'), '')} |\n"
        )
    for name in sorted(described):
        spec = described[name] or {}
        text = text_of(name)
        lines.append(f"\n## `roomba_plus.{name}`\n\n")
        lines.append(f"**{text.get('name', name)}.** {' '.join(text.get('description', '').split())}\n\n")
        response = responses.get(name, "none")
        if response == "only":
            lines.append("Returns data, always: call it with `response_variable`.\n\n")
        elif response == "optional":
            lines.append("Returns data when you ask for it with `response_variable`.\n\n")
        if spec.get("target"):
            lines.append("Target: a Roomba+ vacuum.\n\n")
        fields = spec.get("fields") or {}
        if fields:
            lines.append("| Field | Required | What it is | Example |\n|---|---|---|---|\n")
            for field, fspec in fields.items():
                fspec = fspec or {}
                ftext = text["fields"][field]
                example = fspec.get("example")
                example_cell = f"`{_cell(example)}`" if example not in (None, "") else ""
                lines.append(
                    f"| `{field}` | {'Yes' if fspec.get('required') else ''} "
                    f"| **{_cell(ftext.get('name', field))}.** {_cell(ftext.get('description', ''))} "
                    f"| {example_cell} |\n"
                )
        else:
            lines.append("No fields.\n")
    lines.append(FOOTER)
    return "".join(lines)


