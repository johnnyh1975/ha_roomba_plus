def _platform(path: Path) -> str | None:
    if path.name in PLATFORM_OF_FILE:
        return PLATFORM_OF_FILE[path.name]
    if path.name.startswith("sensor"):
        return "sensor"
    return None


def _kw(call: ast.Call, name: str) -> ast.expr | None:
    for keyword in call.keywords:
        if keyword.arg == name:
            return keyword.value
    return None


def _const(node: ast.expr | None) -> Any:
    return node.value if isinstance(node, ast.Constant) else None


def _uid_tail(node: ast.expr) -> str | None:
    """f"{self.robot_unique_id}_bin_full" -> "bin_full"; None if not fixed."""
    if not isinstance(node, ast.JoinedStr):
        return None
    for i, part in enumerate(node.values):
        if isinstance(part, ast.FormattedValue) and "robot_unique_id" in ast.unparse(part.value):
            rest = node.values[i + 1:]
            if all(isinstance(r, ast.Constant) for r in rest):
                return "".join(str(r.value) for r in rest).lstrip("_")  # type: ignore[attr-defined]
            return None
    return None


def _category(node: ast.expr | None) -> str:
    text = ast.unparse(node) if node is not None else ""
    if text.endswith("DIAGNOSTIC"):
        return "Diagnostic"
    if text.endswith("CONFIG"):
        return "Configuration"
    return ""


class _Class:
    @staticmethod
    def _branch(stmts: list[ast.stmt], default_tk: str | None) -> tuple[str | None, str | None]:
        tk = uid = None
        for stmt in stmts:
            if isinstance(stmt, ast.Assign):
                name = ast.unparse(stmt.targets[0])
                if name.endswith("_attr_translation_key") and _const(stmt.value):
                    tk = _const(stmt.value)
                elif name.endswith("_attr_unique_id"):
                    uid = _uid_tail(stmt.value)
        return tk, uid

    def __init__(self, node: ast.ClassDef, path: Path) -> None:
        self.node = node
        self.path = path
        self.bases = [ast.unparse(b).split(".")[-1] for b in node.bases]
        self.translation_key: str | None = None
        self.uid: str | None = None
        self.suggested: str | None = None
        self.suggested_from_key = False
        self.enabled: bool | None = None
        self.category: ast.expr | None = None
        self.description: ast.Call | None = None
        for stmt in node.body:
            if isinstance(stmt, (ast.Assign, ast.AnnAssign)):
                target = stmt.targets[0] if isinstance(stmt, ast.Assign) else stmt.target
                name = ast.unparse(target)
                if name == "entity_description" and isinstance(stmt.value, ast.Call):
                    self.description = stmt.value
            if isinstance(stmt, ast.FunctionDef) and stmt.name == "suggested_object_id":
                for ret in ast.walk(stmt):
                    if isinstance(ret, ast.Return) and ret.value is not None:
                        if _const(ret.value):
                            self.suggested = _const(ret.value)
                        elif "entity_description.key" in ast.unparse(ret.value) or ".key" in ast.unparse(ret.value):
                            self.suggested_from_key = True
                        break
        class_tk = next((_const(s.value) for s in node.body if isinstance(s, ast.Assign)
                         and ast.unparse(s.targets[0]) == "_attr_translation_key"), None)
        #: One class, two entities: `if include_live: key and id A, else B`.
        self.variants: list[tuple[str, str]] = []
        for sub in ast.walk(node):
            if isinstance(sub, ast.If) and sub.orelse:
                pairs = [self._branch(branch, class_tk) for branch in (sub.body, sub.orelse)]
                if all(pair[1] for pair in pairs) and any(pair[0] for pair in pairs):
                    self.variants = [(tk or class_tk, uid) for tk, uid in pairs]  # type: ignore[misc]
        for sub in ast.walk(node):
            if isinstance(sub, (ast.Assign, ast.AnnAssign)) and sub.value is not None:
                target = sub.targets[0] if isinstance(sub, ast.Assign) else sub.target
                name = ast.unparse(target)
                if name.endswith("_attr_translation_key") and _const(sub.value):
                    self.translation_key = _const(sub.value)
                elif name.endswith("_attr_unique_id"):
                    self.uid = _uid_tail(sub.value) or self.uid
                elif name.endswith("_attr_entity_registry_enabled_default"):
                    if isinstance(_const(sub.value), bool):
                        self.enabled = _const(sub.value)
                elif name.endswith("_attr_entity_category"):
                    self.category = sub.value


def _index() -> tuple[dict[str, _Class], dict[str, Any], dict[str, list[ast.Call]]]:
    classes: dict[str, _Class] = {}
    functions: dict[str, tuple[ast.FunctionDef | ast.AsyncFunctionDef, Path]] = {}
    tuples: dict[str, list[ast.Call]] = {}
    for path in sorted(CC.glob("*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for node in tree.body:
            if isinstance(node, ast.ClassDef):
                classes.setdefault(node.name, _Class(node, path))
            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                if node.name != "async_setup_entry":
                    functions.setdefault(node.name, (node, path))
            elif isinstance(node, (ast.Assign, ast.AnnAssign)) and node.value is not None:
                target = node.targets[0] if isinstance(node, ast.Assign) else node.target
                calls = [c for c in ast.walk(node.value) if isinstance(c, ast.Call)
                         and _const(_kw(c, "translation_key"))]
                if calls and isinstance(target, ast.Name):
                    tuples[target.id] = calls
    return classes, functions, tuples


def _is_prime_test(test: ast.expr) -> bool | None:
    """True for `<is Prime>`, False for `<is not Prime>`, None otherwise."""
    if isinstance(test, ast.UnaryOp) and isinstance(test.op, ast.Not):
        inner = _is_prime_test(test.operand)
        return None if inner is None else not inner
    if isinstance(test, ast.Name) and test.id in ("prime", "is_prime"):
        return True
    text = ast.unparse(test)
    if "CLOUD_ONLY" in text and " and " not in text and " or " not in text:
        return " is not " not in text and "!=" not in text
    return None


class _Reach:
    """Which classes and description tuples each generation's setup creates."""

    def __init__(self, classes: dict[str, _Class], functions: dict[str, Any],
                 tuples: dict[str, list[ast.Call]]) -> None:
        self.classes = classes
        self.functions = functions
        self.tuples = tuples
        self.found: dict[str, set[str]] = {}
        #: Descriptions a Prime path takes from a shared tuple by key:
        #: {tuple name: {key: generations}}.
        self.partial: dict[str, dict[str, set[str]]] = {}
        self._seen: set[tuple[str, str]] = set()
        self._stack: list[tuple[ast.AST, Path]] = []

    def mark(self, name: str, gen: str) -> None:
        gens = {"Classic", "Prime"} if gen == "Both" else {gen}
        if gen == "Prime" and name in self.tuples and self._stack:
            keys = self._key_filter()
            if keys:
                for key in keys:
                    self.partial.setdefault(name, {}).setdefault(key, set()).add("Prime")
                return
        self.found.setdefault(name, set()).update(gens)

    def _key_filter(self) -> set[str]:
        """Keys named by the constants the current function filters with.

        The Prime setup takes some of the Classic descriptions, by key:
        `for d in SENSORS if d.key in _PRIME_MISSION_SENSOR_KEYS`. The
        constants a function names whose value is a set or dict of
        strings are those keys.
        """
        node, path = self._stack[-1]
        module = _module(path)
        keys: set[str] = set()
        for sub in ast.walk(node):
            if isinstance(sub, ast.Name):
                value = vars(module).get(sub.id)
                if isinstance(value, (set, frozenset, dict)) and value and all(
                    isinstance(k, str) for k in value
                ):
                    keys |= set(value)
        return keys

    def expr(self, node: ast.AST, gen: str) -> None:
        if isinstance(node, ast.IfExp):
            prime = _is_prime_test(node.test)
            if prime is not None:
                self.expr(node.test, gen)
                self.expr(node.body, "Prime" if prime else "Classic")
                self.expr(node.orelse, "Classic" if prime else "Prime")
                return
        if isinstance(node, ast.Name):
            if node.id in self.classes or node.id in self.tuples:
                self.mark(node.id, gen)
            if node.id in self.functions:
                self.function(node.id, gen)
        if isinstance(node, ast.Attribute) and node.attr in self.functions:
            self.function(node.attr, gen)
        for child in ast.iter_child_nodes(node):
            self.expr(child, gen)

    def function(self, name: str, gen: str) -> None:
        if (name, gen) in self._seen:
            return
        self._seen.add((name, gen))
        node, path = self.functions[name]
        self._stack.append((node, path))
        try:
            self.block(node.body, gen)
        finally:
            self._stack.pop()

    def block(self, stmts: list[ast.stmt], gen: str) -> None:
        for stmt in stmts:
            if isinstance(stmt, ast.If):
                prime = _is_prime_test(stmt.test)
                if prime is not None:
                    yes, no = ("Prime", "Classic") if prime else ("Classic", "Prime")
                    self.block(stmt.body, yes if gen == "Both" else gen)
                    self.block(stmt.orelse, no if gen == "Both" else gen)
                    if gen == "Both" and any(isinstance(s, ast.Return) for s in stmt.body):
                        gen = no
                    continue
                self.expr(stmt.test, gen)
                self.block(stmt.body, gen)
                self.block(stmt.orelse, gen)
            elif isinstance(stmt, (ast.For, ast.AsyncFor, ast.While, ast.With, ast.AsyncWith)):
                for field in ("iter", "test"):
                    if hasattr(stmt, field):
                        self.expr(getattr(stmt, field), gen)
                for item in getattr(stmt, "items", []):
                    self.expr(item, gen)
                self.block(stmt.body, gen)
                self.block(getattr(stmt, "orelse", []), gen)
            elif isinstance(stmt, ast.Try):
                self.block(stmt.body, gen)
                for handler in stmt.handlers:
                    self.block(handler.body, gen)
                self.block(stmt.orelse, gen)
                self.block(stmt.finalbody, gen)
            elif isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef)):
                self.block(stmt.body, gen)  # a callback defined in setup
            else:
                self.expr(stmt, gen)


def _robots(gens: set[str]) -> str:
    if gens == {"Classic", "Prime"}:
        return "Both"
    return next(iter(gens)) if gens else ""


def _module(path: Path) -> Any:
    sys.path.insert(0, str(ROOT))
    import importlib  # noqa: PLC0415

    return importlib.import_module(f"custom_components.roomba_plus.{path.stem}")


def _class_attr(cls: Any, name: str) -> Any:
    """A class default of an `_attr_*` attribute. Home Assistant turns
    those into properties and keeps the value as `__attr_*`."""
    value = getattr(cls, name, None)
    if isinstance(value, property):
        value = getattr(cls, "_" + name, None)
    return value


def _category_of(value: Any) -> str:
    text = str(getattr(value, "value", value) or "")
    return {"diagnostic": "Diagnostic", "config": "Configuration"}.get(text, "")


