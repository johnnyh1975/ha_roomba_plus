#!/usr/bin/env python3
"""Write the reference pages that are generated from the code (4.6.0).

    python scripts/build_reference.py           write docs/reference/*.md
    python scripts/build_reference.py --check   fail if a page is out of date

Three pages, each from the place Home Assistant itself reads:

- docs/reference/actions.md: every action in services.yaml, with the
  name, description and fields the action editor shows (strings.json),
  the example from services.yaml and whether the action returns data;
- docs/reference/options.md: every step of Configure, with the option
  names and explanations from strings.json, in menu order;
- docs/reference/entities.md: every entity with a name in strings.json,
  with the entity id the integration gives it, the robots that get it,
  whether it starts disabled and its category.

Why generated: the hand-written lists drifted. The 4.6.0 review found
about twenty entity ids and actions in the docs that the code did not
have. A page written from the code cannot drift; the test
(tests/test_build_reference.py) fails when somebody changes an entity,
an action or an option and does not run this script.

Which robots get an entity is read from each platform's
`async_setup_entry`: what it creates inside the branch for a cloud-only
(Prime) robot is Prime, what it creates on the other path is Classic,
what it creates before the branch is both. Whether a particular robot
gets it also depends on the model and the options; the pages say so.

Needs Home Assistant importable for the actions page (it asks the
action registration which actions return data), so run it with the
Python the tests use.
"""
