def entity_rows() -> list[dict[str, str]]:
    """One row per entity: per name in strings.json and per id it gets."""
    classes, functions, tuples = _index()
    reach = _Reach(classes, functions, tuples)
    for path in sorted(CC.glob("*.py")):
        if _platform(path) is None:
            continue
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for node in tree.body:
            if isinstance(node, ast.AsyncFunctionDef) and node.name == "async_setup_entry":
                reach.block(node.body, "Both")
    # A class created by the setup carries its generation to the
    # descriptions it names (`super().__init__(..., _PASSES_DESC)`).
    owner: dict[str, _Class] = {}
    for name, gens in list(reach.found.items()):
        if name in classes:
            for node in ast.walk(classes[name].node):
                if isinstance(node, ast.Name) and node.id in tuples:
                    owner[node.id] = classes[name]
                    for gen in gens:
                        reach.mark(node.id, gen)

    candidates: dict[tuple[str, str, str, bool, str], dict[str, Any]] = {}

    def add(platform: str, tk: str, suffix: str | None, gens: set[str],
            enabled: Any, category: Any) -> None:
        suffix = suffix or ""  # built at run time: DYNAMIC has its pattern
        # Keyed on how the entity starts too: the same id can be a
        # diagnostic on one generation and not on the other.
        flags = (enabled is not False, _category_of(category))
        row = candidates.setdefault((platform, tk, suffix, *flags), {
            "gens": set(), "enabled": flags[0], "category": flags[1],
        })
        row["gens"] |= gens

    def inherited(cls: _Class, attr: str) -> Any:
        """The first value of `attr` up the class's bases in this package."""
        seen: set[str] = set()
        todo = [classes[b] for b in cls.bases if b in classes]
        while todo:
            current = todo.pop(0)
            if current.node.name in seen:
                continue
            seen.add(current.node.name)
            value = getattr(current, attr)
            if value:
                return value
            todo += [classes[b] for b in current.bases if b in classes]
        return None

    for cls in classes.values():
        platform = _platform(cls.path)
        if platform is None or cls.node.name not in reach.found:
            continue
        runtime = getattr(_module(cls.path), cls.node.name)
        desc = getattr(runtime, "entity_description", None)
        # A subclass that only changes where the data comes from (the
        # Prime variant of a Classic sensor) inherits key and id.
        tk = (cls.translation_key or inherited(cls, "translation_key")
              or getattr(desc, "translation_key", None))
        if not tk:
            continue
        key = getattr(desc, "key", None)
        suffix = (cls.suggested or inherited(cls, "suggested")
                  or (key if cls.suggested_from_key else None)
                  or cls.uid or inherited(cls, "uid")
                  or getattr(desc, "unique_id_suffix", None) or key)
        enabled = cls.enabled
        if enabled is None:
            enabled = _class_attr(runtime, "_attr_entity_registry_enabled_default")
        if enabled is None and desc is not None:
            enabled = desc.entity_registry_enabled_default
        category = cls.category
        category = (_class_attr(runtime, "_attr_entity_category")
                    if category is None else ast.unparse(category).rsplit(".", 1)[-1].lower())
        if category is None and desc is not None:
            category = desc.entity_category
        if cls.variants:
            for variant_tk, variant_uid in cls.variants:
                add(platform, variant_tk, variant_uid, reach.found[cls.node.name], enabled, category)
            continue
        add(platform, tk, suffix, reach.found[cls.node.name], enabled, category)

    for path in sorted(CC.glob("*.py")):
        platform = _platform(path)
        if platform is None:
            continue
        module = _module(path)
        for name in tuples:
            if (name not in reach.found and name not in reach.partial) or name not in vars(module):
                continue
            value = vars(module)[name]
            for desc in value if isinstance(value, (tuple, list)) else (value,):
                tk = getattr(desc, "translation_key", None)
                gens = reach.found.get(name, set()) | reach.partial.get(name, {}).get(desc.key, set())
                if not tk or not gens:
                    continue
                suffix = getattr(desc, "unique_id_suffix", None) or desc.key
                category = desc.entity_category
                if category is None and name in owner:
                    owned = getattr(_module(owner[name].path), owner[name].node.name)
                    category = _class_attr(owned, "_attr_entity_category")
                add(platform, tk, suffix, gens, desc.entity_registry_enabled_default, category)

    rows: list[dict[str, str]] = list(UNNAMED)
    names = _strings()["entity"]
    code = "\n".join(p.read_text(encoding="utf-8") for p in CC.glob("*.py"))
    for (platform, tk), (pattern, _robots_, _cls) in DYNAMIC.items():
        evidence = EVIDENCE.get(pattern, (pattern.split("<")[0].rstrip("_"),))
        if not all(e in code for e in evidence) or tk not in names.get(platform, {}):
            raise SystemExit(f"DYNAMIC {platform}.{tk}: {pattern!r} is not in the code any more")
    seen: set[tuple[str, str, str]] = set()
    for (platform, tk, suffix, *_), row in sorted(candidates.items()):
        if tk not in names.get(platform, {}):
            continue
        if (platform, tk) in DYNAMIC:
            suffix = DYNAMIC[(platform, tk)][0]
        elif not suffix:
            raise SystemExit(f"{platform}.{tk}: the id is built at run time; add it to DYNAMIC")
        seen.add((platform, tk, suffix))
        rows.append({
            "platform": platform, "key": tk, "suffix": suffix,
            "name": names[platform][tk].get("name", ""),
            "robots": _robots(row["gens"]) or DYNAMIC.get((platform, tk), ("", "", ""))[1],
            "enabled": "" if row["enabled"] else "Off",
            "category": row["category"],
        })
    for (platform, tk), (pattern, robots, cls_name) in DYNAMIC.items():
        if not any(k[:2] == (platform, tk) for k in seen):
            enabled, category = True, ""
            if cls_name:
                runtime = getattr(_module(classes[cls_name].path), cls_name)
                enabled = _class_attr(runtime, "_attr_entity_registry_enabled_default") is not False
                category = _category_of(_class_attr(runtime, "_attr_entity_category"))
            rows.append({
                "platform": platform, "key": tk, "suffix": pattern,
                "name": names[platform][tk].get("name", ""), "robots": robots,
                "enabled": "" if enabled else "Off", "category": category,
            })
    # One row per named Prime part: the id has the part number.
    # The cloud names a part by number or, on newer robots, by word; one
    # row per part with every id it can have, `|`-separated.
    known_parts = vars(_module(CC / f"{KNOWN_PARTS_MODULE}.py"))["_KNOWN_PARTS"]
    by_role: dict[str, list[str]] = {}
    for part_id, tk in known_parts.items():
        by_role.setdefault(tk, []).append(part_id)
    for tk, part_ids in sorted(by_role.items()):
        part_ids.sort(key=lambda p: (not p.isdigit(), int(p) if p.isdigit() else 0, p))
        rows.append({
            "platform": "sensor", "key": tk,
            "suffix": "|".join(f"prime_part_{p}" for p in part_ids),
            # Three roles have no entry in strings.json (sensor_prime says
            # why); the to-do list writes them like this.
            "name": names["sensor"].get(tk, {}).get("name")
            or tk.removeprefix("prime_part_").replace("_", " ").title(),
            "robots": "Prime", "enabled": "", "category": "Diagnostic",
        })
    for row in rows:
        if row["key"] == "prime_consumable_part":
            row["category"] = "Diagnostic"  # set in __init__ with the part
    return rows


PLATFORM_TITLES = {
    "sensor": "Sensors", "binary_sensor": "Binary sensors", "button": "Buttons",
    "select": "Selects", "switch": "Switches", "image": "Images (maps)",
    "calendar": "Calendars", "todo": "To-do lists", "event": "Events",
    "device_tracker": "Device tracker", "vacuum": "Vacuum",
}


def entities_page() -> str:
    rows = entity_rows()
    lines = [HEADER.format(title="Entities")]
    lines.append(
        "Every entity Roomba+ can create, with the id it gets. `<robot>` "
        "stands for your robot's name as Home Assistant writes it in an "
        "id: a robot called *Kitchen Roomba* gives "
        "`sensor.kitchen_roomba_battery`. The ids are English in every "
        "language, so an automation works whatever language Home "
        "Assistant is set to.\n\n"
        "**Robots** says which robots can get the entity: Classic (local "
        "connection), Prime (iRobot cloud) or both. Whether yours gets it "
        "also depends on the model and on the options: a robot without a "
        "mop has no mop sensors, and some entities exist only while their "
        "option is on ([Options](options.md)). **Starts** says *Off* for "
        "entities that are created disabled: turn them on on the device "
        "page. **Category** is where the device page lists them.\n\n"
        "An entity whose id ends in `<…>` exists once per room, area, "
        "part, favourite or schedule.\n\n"
    )
    by_platform: dict[str, list[dict[str, str]]] = {}
    for row in rows:
        by_platform.setdefault(row["platform"], []).append(row)
    order = [p for p in PLATFORM_TITLES if p in by_platform]
    lines.append(" · ".join(f"[{PLATFORM_TITLES[p]}](#{_anchor(PLATFORM_TITLES[p])})"
                            for p in order) + "\n")
    for platform in order:
        lines.append(f"\n## {PLATFORM_TITLES[platform]}\n\n")
        lines.append("| Entity id | Name | Robots | Starts | Category |\n|---|---|---|---|---|\n")
        for row in sorted(by_platform[platform], key=lambda r: (r["suffix"] or r["key"], r["robots"])):
            if platform in ("device_tracker", "vacuum"):
                ident = f"{platform}.<robot>"
            else:
                ident = "` or `".join(f"{platform}.<robot>_{suffix}"
                                      for suffix in row["suffix"].split("|"))
            lines.append(
                f"| `{ident}` | {_cell(row['name'])} | {row['robots']} "
                f"| {row['enabled']} | {row['category']} |\n"
            )
    lines.append(FOOTER)
    return "".join(lines)


PAGES = {
    "actions.md": actions_page,
    "options.md": options_page,
    "entities.md": entities_page,
}


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    OUT.mkdir(parents=True, exist_ok=True)
    for name, build in PAGES.items():
        text = build()
        path = OUT / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8")
    if stale:
        print("Out of date: " + ", ".join(f"docs/reference/{n}" for n in stale)
              + ". Run: python scripts/build_reference.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
