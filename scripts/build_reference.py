def _anchor(title: str) -> str:
    slug = re.sub(r"[^\w\- ]", "", title.lower()).replace(" ", "-")
    return slug


def options_page() -> str:
    steps = _strings()["options"]["step"]
    menu = steps["init"]["menu_options"]
    lines = [HEADER.format(title="Options")]
    lines.append(
        "Everything under **Settings → Devices & services → Roomba+ → "
        "Configure**, in the order of the menu. Some entries and options "
        "appear only for the robots and setups they apply to.\n\n"
        "What leaving an option off costs you: "
        "[What leaving an option off costs you](../explanations/options.md).\n\n"
    )
    lines.append("| Menu entry | Step |\n|---|---|\n")
    order: list[tuple[str, str]] = []
    for key, label in menu.items():
        order.append((key, f"Configure → {label}"))
        step = steps.get(key, {})
        for sub_key, sub_label in (step.get("menu_options") or {}).items():
            order.append((sub_key, f"Configure → {label} → {sub_label}"))
        for sub, (parent, when) in SUB_STEPS.items():
            if parent == key:
                order.append((sub, f"Configure → {label} ({when})"))
    # GitHub numbers a repeated heading: demand-cleaning, demand-cleaning-1.
    anchors: dict[str, str] = {}
    used: dict[str, int] = {}
    for key, _path in order:
        if key in steps and key not in anchors:
            base = _anchor(steps[key].get("title", key))
            anchors[key] = base if base not in used else f"{base}-{used[base]}"
            used[base] = used.get(base, 0) + 1
    for key, path in order:
        if key not in steps:
            continue  # a menu entry that only leads on to one of its steps
        title = steps[key].get("title", key)
        lines.append(f"| {_cell(path)} | [{_cell(title)}](#{anchors[key]}) |\n")
    seen: set[str] = set()
    for key, path in order:
        step = steps.get(key)
        if not step or key in seen:
            continue
        seen.add(key)
        lines.append(f"\n## {step.get('title', key)}\n\n")
        lines.append(f"*{path}*\n\n")
        if step.get("description"):
            desc = step["description"].strip()
            lines.append(desc.replace("\n", "\n\n") + "\n\n")
        data = step.get("data") or {}
        explain = step.get("data_description") or {}
        if data:
            lines.append("| Option | What it does |\n|---|---|\n")
            for field, label in data.items():
                lines.append(f"| **{_cell(label)}** | {_cell(explain.get(field, ''))} |\n")
    lines.append(FOOTER)
    return "".join(lines)


